# frozen_string_literal: true

# The record codec emitter (building block C2): turns the catalog into the C
# in src/ring_proto.h and src/ring_proto.c.
#
# What it emits, per message: the wire struct (the record's fixed part, byte
# for byte), a data struct (scalars by value, spans as ta_bytes), and the
# functions size, write and get. Once for all messages: the kind, flag and enum
# constants and the one static const descriptor table that the hand-written
# checker src/record.c interprets. The checker is not generated: the one place
# hostile bytes are judged is the same thirty lines for every message.
#
# The emitter only formats what the model already computed (layout, offsets,
# sizes: dsl.rb) and asserts what the C side assumes; it takes no host
# information and no clock, so two runs give the same bytes. Every `_Static_assert`
# in the output restates a number the catalog computed, so a change to dsl.rb's
# layout rules that the C does not follow fails to compile.
module RingProto
  module Codec
    module_function

    GENERATED = "GENERATED FILE. Do not edit.\n" \
                'Generated by `mise run protocol` in tinyactors-core from protocol/catalog.rb ' \
                '(the definition of every record) with protocol/codec.rb (this emitter). To ' \
                'change a record, edit the catalog and run the task; `mise run protocol --check` ' \
                'fails when this file is out of date.'

    # C types of the scalars a field can have. i32 is in the DSL but no
    # record uses it yet; add it here with a loader when one does.
    SCALAR_C = {
      u8: 'uint8_t', u16: 'uint16_t', u32: 'uint32_t', u64: 'uint64_t', bool: 'uint8_t',
      time: 'uint64_t', seq: 'uint64_t', session: 'uint64_t', macrostep: 'uint64_t', vref: 'uint64_t', blob: 'uint64_t'
    }.freeze
    SPAN_TYPES = %i[span text bytes].freeze
    MAX_SPANS = 7
    DOMAIN_BITS = 64

    ASCII = { '’' => "'", '‘' => "'", '“' => '"', '”' => '"', '→' => '->', '—' => '--', '–' => '-', '…' => '...',
              '×' => 'x', '≥' => '>=', '≤' => '<=' }.freeze

    # One field of a message, with everything the C needs about it.
    Field = Struct.new(:name, :type, :doc, :offset, :ctype, :kind, :mask, :enum, :size, keyword_init: true) do
      def span? = kind == :span
      def checked? = kind == :enum || kind == :bool
    end

    # One message with its fields classified.
    Info = Struct.new(:msg, :c, :fields, :kind_const, :flags_allowed, keyword_init: true) do
      def spans = fields.select(&:span?)
      def domains = fields.select(&:checked?)
      def type = "ta_msg_#{c}"
      def wire = "ta_msg_#{c}_wire"
    end

    def c_name(id) = id.tr('.', '_')

    def hex(code) = format('0x%04X', code)

    # Comment text must be plain ASCII and must not end the comment early.
    def ascii(text)
      out = text.dup
      ASCII.each { |from, to| out.gsub!(from, to) }
      raise "non-ASCII text in the catalog: #{out.inspect}" unless out.ascii_only?
      raise "comment terminator in the catalog: #{out.inspect}" if out.include?('*/')

      out
    end

    # Word-wrapped comment body lines, each prefixed with ` * `. A line that
    # starts with spaces (a list entry, a line of code) is kept as it is when
    # it fits, and otherwise wrapped with a hanging indent.
    def wrap(text, width = 76, prefix = ' * ')
      lines = []
      ascii(text).split("\n", -1).each do |paragraph|
        indent = paragraph[/\A */]
        if indent.empty?
          wrap_words(paragraph, width, '', lines)
        elsif paragraph.size <= width
          lines << paragraph
        else
          wrap_words(paragraph.strip, width, indent, lines)
        end
      end
      lines.map { |line| line.strip.empty? ? prefix.rstrip : "#{prefix}#{line}" }.join("\n")
    end

    def wrap_words(paragraph, width, indent, lines)
      hang = indent.empty? ? '' : "#{indent}    "
      line = indent.dup
      paragraph.split(' ').each do |word|
        if line.strip != '' && line.size + 1 + word.size > width
          lines << line
          line = hang.dup
        end
        line << ' ' unless line.strip.empty?
        line << word
      end
      lines << line
    end

    def comment(text) = "/*\n#{wrap(text.rstrip)}\n */\n"

    def one_line(text) = "/* #{ascii(text)} */"

    def classify(model, msg)
      fields = msg.fields.map do |f|
        enum = model.enums[f.type]
        base = enum ? enum.base : f.type
        if SPAN_TYPES.include?(f.type)
          Field.new(name: f.name, type: f.type, doc: f.doc, offset: f.offset, ctype: 'ta_span32', kind: :span, size: 8)
        else
          ctype = SCALAR_C[base] or raise "#{msg.id}.#{f.name}: no C type for #{base}; add it to Codec::SCALAR_C"
          kind = enum ? :enum : (base == :bool ? :bool : :scalar)
          mask = enum ? enum.values.sum { |v| 1 << v.value } : (base == :bool ? 3 : nil)
          if enum && enum.values.any? { |v| v.value >= DOMAIN_BITS }
            raise "#{enum.name}: a value of #{DOMAIN_BITS} or more does not fit the 64-bit domain mask"
          end

          Field.new(name: f.name, type: f.type, doc: f.doc, offset: f.offset, ctype: ctype, kind: kind, mask: mask,
                    enum: enum, size: model.size_of(f.type))
        end
      end
      raise "#{msg.id}: a field named head collides with the data struct's header part" if fields.any? { |f| f.name == :head }

      flags = msg.flags.sum { |f| 1 << f.bit } | COMMON_FLAGS.sum { |f| 1 << f.bit }
      Info.new(msg: msg, c: c_name(msg.id), fields: fields, kind_const: "TA_MSG_#{c_name(msg.id).upcase}", flags_allowed: flags)
    end

    # Everything the C refers to by number is checked against the C side here.
    def check_model!(model, infos)
      infos.each do |info|
        raise "#{info.msg.id}: #{info.spans.size} spans, the checker's descriptor holds #{MAX_SPANS}" if info.spans.size > MAX_SPANS
        raise "#{info.msg.id}: fixed size #{info.msg.fixed_size} is not a multiple of 8" unless (info.msg.fixed_size % 8).zero?
      end
      max = infos.map { |i| i.msg.fixed_size }.max
      raise "largest fixed part is #{max}; TA_RECORD_FIXED_MAX is #{FIXED_MAX}" if max > FIXED_MAX
    end

    # TA_RECORD_FIXED_MAX in src/record.h.
    FIXED_MAX = 128

    def infos(model) = model.messages.map { |msg| classify(model, msg) }

    # ------------------------------------------------------------ header

    def header(model)
      infos = infos(model)
      check_model!(model, infos)
      out = +"/*\n#{wrap(GENERATED.rstrip)}\n */\n#pragma once\n\n"
      out << "#include \"types.h\"\n#include \"ring.h\"\n#include \"record.h\"\n\n"
      out << package_comment(model, infos)
      out << kinds(model)
      out << common_flags
      out << message_flags(infos)
      out << enums(model)
      out << wire_header
      infos.each { |info| out << message_header(model, info) }
      out << table_declaration
      out
    end

    def table_declaration
      out = +"/*\n * ta_msg_table returns the descriptors of every message in this build, sorted by\n"
      out << " * kind, for ta_record_reader_init. The table is static const data (system\n"
      out << " * lifetime): the pointer stays valid for as long as the library is loaded.\n */\n"
      out << "const ta_record_table *ta_msg_table(void);\n"
    end

    def package_comment(model, infos)
      text = <<~TEXT
        Package ring_proto is the typed codec for the records that cross the rings: for each of the #{infos.size} messages of the protocol catalog, the struct of its fixed part, a data struct, and the functions that measure, write and read it. It is generated (see the header above), and it is built on the hand-written checker in src/record.h, which is where bytes from outside are judged. The protocol is tinyactors-core/protocol/README.md; the generated reference, with every field's meaning, is tinyactors-core/protocol/generated/MESSAGES.md.

        What each message gets. ta_msg_<name>_wire is the fixed part exactly as it sits in a record (the header, fields at their natural alignment, explicit pad bytes), with a _Static_assert on its size and on the offset of every field. ta_msg_<name> is what code works with: scalars by value, every text or bytes span as a ta_bytes view, and the header fields a caller chooses (flags, session, at) in ta_msg_head. Size, write and get:

          ta_msg_<name>_size(data, &size)    the exact size of the record, a multiple of 8
          ta_msg_<name>_write(data, &to)     fill a ring reservation of exactly that size
          ta_msg_<name>_get(&record, &out)   decode a record that ta_record_check accepted

        Lifetimes and allocation. Nothing here allocates, ever; the functions take no allocator, and a failing allocator cannot affect them. The data structs are call-lifetime values. On the write side the ta_bytes are read during the call and copied into the record, so the caller's text may be freed as soon as write returns; they must not overlap the reservation. On the get side the scalars are copies and may outlive the record, but every ta_bytes points into the record's bytes and dies when the record is released (ta_ring_release). A ta_record_reader and the descriptor table behind ta_msg_table() have system lifetime; the table is static const data.

        Size. ta_msg_<name>_size lays the record out with a ta_layout (the fixed part at alignment 8, one entry per span at alignment 1, then a round up to 8), so a length that overflows is TA_ERR_NOMEM and never a wrapped number; it also answers TA_ERR_NOMEM when the total does not fit a u32, the size field's width. TA_ERR_INVALID means a ta_bytes with a length and no pointer. *size is untouched on failure.

        Write. The caller reserves exactly the measured size on the message's ring (ta_ring_reserve), calls write, and commits (ta_ring_commit); on any failure write has stored nothing, so abandoning the reservation is exact. Every byte of the reservation is stored: reserved ring bytes are stale, and a stale pad byte would leak to the host and make replay depend on history, so every pad and rounding byte is zeroed. Write also stores the size and the seq, the same values ta_ring_commit stores, so a written record is complete without a ring and can be tested alone. TA_ERR_INVALID: the reservation has no bytes or is not of the exact size, a flag bit is not defined for the message, an enum or bool field holds a value outside its set (such a record would be refused by the reader), or a ta_bytes is malformed.

        Get. A record that ta_record_check accepted has every span inside it, every enum in range and the fixed part in its snapshot; get decodes from the snapshot only (no double fetch). It answers TA_ERR_INVALID only when the record is of another kind. The bytes behind a span stay untrusted for as long as they exist, and text is not checked for UTF-8.

        Complexity. Every function is O(fixed fields + spans) plus the copy of the span bytes, with no recursion and O(1) stack (the largest wire struct is #{FIXED_MAX} bytes).

        Example, writing and reading a c2h record:

          ta_msg_c2h_log log = { .head = { .session = id }, .text = { text, text_length } };
          uint32_t size;
          ta_msg_c2h_log_size(&log, &size);
          ta_ring_reservation to;
          if (ta_ring_reserve(&rings.ring[TA_RING_C2H], size, &to) == TA_RING_OK) {
              ta_msg_c2h_log_write(&log, &to);
              ta_ring_commit(&rings.ring[TA_RING_C2H]);
          }
      TEXT
      comment(text)
    end

    def kinds(model)
      out = +"/* The header's kind: the message code. Kind 0 is the ring's pad record and is not a message. */\n"
      out << "typedef enum ta_msg_kind {\n"
      model.messages.each { |m| out << "    TA_MSG_#{c_name(m.id).upcase} = #{hex(m.code)},\n" }
      out << "} ta_msg_kind;\n\n"
    end

    def common_flags
      out = +"/* Flags any record may carry: bits 8..15 of the header's flags. */\n"
      out << "typedef enum ta_msg_common_flag {\n"
      COMMON_FLAGS.each { |f| out << "    TA_MSG_FLAG_#{f.name.upcase} = 1 << #{f.bit}, #{one_line(first_sentence(f.doc))}\n" }
      out << "} ta_msg_common_flag;\n\n"
    end

    def first_sentence(text) = text.split(/(?<=\.)\s/).first.to_s.sub(/\.\z/, '')

    def message_flags(infos)
      infos.reject { |i| i.msg.flags.empty? }.map do |info|
        prefix = info.kind_const
        out = +"/* #{info.msg.id}'s own flags: bits 0..7 of the header's flags. */\n"
        out << "typedef enum #{info.type}_flag {\n"
        info.msg.flags.each { |f| out << "    #{prefix}_#{f.name.upcase} = 1 << #{f.bit}, #{one_line(f.doc)}\n" }
        out << "} #{info.type}_flag;\n\n"
      end.join
    end

    # One C enum per catalog enum. Fields of the structs stay fixed-width
    # integers (the size of a C enum is up to the compiler); a comment names
    # the enum a field holds.
    def enums(model)
      model.enums.each_value.map do |e|
        out = +"/* #{ascii(e.doc.empty? ? e.name.to_s : e.doc)} Stored as #{SCALAR_C.fetch(e.base)}. */\n"
        out << "typedef enum ta_msg_#{e.name} {\n"
        e.values.each do |v|
          out << "    TA_MSG_#{e.name.upcase}_#{v.name.upcase} = #{v.value},#{v.doc.empty? ? '' : " #{one_line(v.doc)}"}\n"
        end
        out << "} ta_msg_#{e.name};\n\n"
      end.join
    end

    def wire_header
      out = +"/* The common header, as it sits at the start of every record: 32 bytes, no padding. */\n"
      out << "typedef struct ta_msg_wire_header {\n"
      HEADER.each do |f|
        comment = f.name == :kind ? ' /* ta_msg_kind */' : ''
        out << "    #{SCALAR_C.fetch(f.type)} #{f.name};#{comment}\n"
      end
      out << "} ta_msg_wire_header;\n_Static_assert(sizeof(ta_msg_wire_header) == #{HEADER_SIZE}, \"header\");\n\n"
      out << "/* The header fields a caller chooses; kind and size come from the message, seq from the reservation. */\n"
      out << "typedef struct ta_msg_head {\n    uint16_t flags; /* the message's flags (bits 0..7) and the common flags (bits 8..15) */\n"
      out << "    uint64_t session;\n    uint64_t at;\n} ta_msg_head;\n\n"
    end

    # ------------------------------------------------------------ source

    def source(model)
      infos = infos(model)
      check_model!(model, infos)
      out = +"/*\n#{wrap(GENERATED.rstrip)}\n */\n#include \"ring_proto.h\"\n\n"
      infos.each { |info| out << size_function(info) << write_function(info) << get_function(info) }
      out << descriptor_table(infos)
      out
    end

    def descriptor_table(infos)
      sorted = infos.sort_by { |i| i.msg.code }
      out = +"/* The descriptors: what ta_record_check interprets. The arrays are static const data, system lifetime. */\n\n"
      sorted.each { |info| out << message_descriptor_arrays(info) }
      out << "/* One descriptor per message, sorted by kind (ta_record_reader_init checks it). */\n"
      out << "static const ta_record_descriptor ta_msg_descriptors[] = {\n"
      sorted.each { |info| out << descriptor_entry(info) }
      out << "};\n"
      out << "_Static_assert(sizeof ta_msg_descriptors / sizeof ta_msg_descriptors[0] == #{infos.size}, \"every message has a descriptor\");\n\n"
      out << "static const ta_record_table ta_msg_table_value = { ta_msg_descriptors, #{infos.size} };\n\n"
      out << "/* ta_msg_table returns the table of all #{infos.size} messages. It is static const data and outlives every reader. */\n"
      out << "const ta_record_table *ta_msg_table(void) {\n    return &ta_msg_table_value;\n}\n"
      out
    end

    # The span offsets and the enum and bool domains of one message, as arrays (none when it has none).
    def message_descriptor_arrays(info)
      out = +''
      unless info.spans.empty?
        out << "static const ta_record_span_at #{info.type}_spans[] = { #{info.spans.map { |f| "{ #{f.offset} }" }.join(', ')} };\n"
      end
      unless info.domains.empty?
        out << "static const ta_record_domain #{info.type}_domains[] = { " \
               "#{info.domains.map { |f| format('{ %d, 0x%Xull }', f.offset, f.mask) }.join(', ')} };\n"
      end
      out
    end

    def descriptor_entry(info)
      msg = info.msg
      spans = info.spans.empty? ? 'NULL' : "#{info.type}_spans"
      domains = info.domains.empty? ? 'NULL' : "#{info.type}_domains"
      "    { .kind = #{info.kind_const}, .ring = TA_RING_#{msg.ring.to_s.upcase}, .span_count = #{info.spans.size}, " \
        "#{'.domain_count = %d, ' % info.domains.size}.fixed_size = #{msg.fixed_size}, " \
        "#{format('.flags_allowed = 0x%04X, ', info.flags_allowed)}.spans = #{spans}, .domains = #{domains} },\n"
    end

    # ---------------------------------------------------------- size

    def size_prototype(info)
      spans = info.spans
      text = +"#{info.type}_size sets *size to the exact size in bytes of the #{info.msg.id} record that\n"
      text << "#{info.type}_write stores for data: #{info.msg.fixed_size} fixed bytes"
      text << if spans.empty?
                ', so always that many'
              else
                " and the #{spans.size} spans' bytes (#{spans.map(&:name).join(', ')}), rounded up to a multiple of 8"
              end
      text << '. It never allocates. '
      text << if spans.empty?
                'It cannot fail. '
              else
                'TA_ERR_NOMEM: the total does not fit a u32 (or size_t), and *size is untouched. ' \
                'TA_ERR_INVALID: a ta_bytes has a length and no pointer, and *size is untouched. '
              end
      text << 'data and size must not be NULL.'
      "#{comment(text)}ta_result #{info.type}_size(const #{info.type} *data, uint32_t *size);\n\n"
    end

    # The size is the fixed part, then each span's bytes at alignment 1, then a
    # round up to 8, measured by a ta_layout so that no length can wrap.
    def size_function(info)
      out = +"/* #{info.type}_size: see ring_proto.h. */\n"
      out << "ta_result #{info.type}_size(const #{info.type} *data, uint32_t *size) {\n"
      if info.spans.empty?
        out << "    (void)data;\n    *size = #{info.msg.fixed_size};\n    return TA_OK;\n}\n\n"
        return out
      end
      out << "    ta_layout layout;\n    size_t bytes = 0;\n    ta_result result;\n"
      out << "    if (#{info.spans.map { |f| "!ta_record_bytes_ok(data->#{f.name})" }.join(" ||\n        ")}) {\n"
      out << "        return TA_ERR_INVALID;\n    }\n"
      out << "    ta_layout_init(&layout, 0);\n"
      out << "    ta_layout_add(&layout, &(ta_layout_entry){ .size = #{info.msg.fixed_size}, .alignment = 8, .count = 1 });\n"
      info.spans.each do |f|
        out << "    ta_layout_add(&layout, &(ta_layout_entry){ .size = 1, .alignment = 1, .count = data->#{f.name}.len });\n"
      end
      out << "    ta_layout_add(&layout, &(ta_layout_entry){ .size = 1, .alignment = 8, .count = 0 }); /* round up to 8 */\n"
      out << "    result = ta_layout_finish(&layout, &bytes, NULL);\n    if (result != TA_OK) {\n        return result;\n    }\n"
      out << "    if ((uint64_t)bytes > UINT32_MAX) {\n        return TA_ERR_NOMEM;\n    }\n"
      out << "    *size = (uint32_t)bytes;\n    return TA_OK;\n}\n\n"
    end

    # ---------------------------------------------------------- write

    def write_prototype(info)
      text = +"#{info.type}_write fills the reservation `to` with the #{info.msg.id} record for data: the header "
      text << "(kind #{hex(info.msg.code)}, the flags, session and at of data->head, the size, and the seq of the reservation), "
      text << 'the fixed fields, the bytes of each span, and zero for every pad and rounding byte, so that all of to->size bytes are stored. '
      text << "It needs a reservation of exactly the size #{info.type}_size answers (ring.h: ta_ring_reserve), "
      text << 'and the ta_bytes of data must not overlap it. '
      text << 'TA_ERR_INVALID, with nothing stored: no bytes, a size other than the measured one, a flag bit that '
      text << "#{info.msg.id} does not define, "
      text << 'an enum or bool field outside its set (the reader would refuse the record), or a ta_bytes with a length and no pointer. '
      text << 'TA_ERR_NOMEM, with nothing stored: the size does not fit a u32. '
      text << 'The caller then commits the reservation, or abandons it on an error. It never allocates, and the data may be freed when it returns.'
      "#{comment(text)}ta_result #{info.type}_write(const #{info.type} *data, const ta_ring_reservation *to);\n\n"
    end

    # All checks come before the first store, so a refusal leaves the reservation as it was.
    def write_function(info)
      out = +"/* #{info.type}_write: see ring_proto.h. */\n"
      out << "ta_result #{info.type}_write(const #{info.type} *data, const ta_ring_reservation *to) {\n"
      out << "    #{info.wire} wire;\n    uint32_t size = 0;\n    uint32_t tail = (uint32_t)sizeof wire;\n"
      out << "    ta_result result = #{info.type}_size(data, &size);\n"
      out << "    if (result != TA_OK) {\n        return result;\n    }\n"
      conditions = ['to->bytes == NULL', 'to->size != size',
                    format('(data->head.flags & (uint16_t)~0x%04Xu) != 0', info.flags_allowed)]
      info.domains.each { |f| conditions << format('!ta_record_in_domain(0x%Xull, data->%s)', f.mask, f.name) }
      out << "    if (#{conditions.join(" ||\n        ")}) {\n        return TA_ERR_INVALID;\n    }\n"
      out << "    ta_mem_zero(&wire, sizeof wire);\n"
      info.spans.each { |f| out << "    tail = ta_record_put_span(&wire.#{f.name}, to->bytes, tail, data->#{f.name});\n" }
      out << "    wire.header = (ta_msg_wire_header){ .kind = #{info.kind_const}, .flags = data->head.flags, .size = size,\n"
      out << "                                        .seq = to->seq, .session = data->head.session, .at = data->head.at };\n"
      info.fields.reject(&:span?).each { |f| out << "    wire.#{f.name} = data->#{f.name};\n" }
      out << "    ta_mem_copy(to->bytes, &wire, sizeof wire);\n"
      out << "    ta_mem_zero(to->bytes + tail, size - tail);\n    return TA_OK;\n}\n\n"
    end

    # ------------------------------------------------------------ get

    LOADER = { 'uint8_t' => 'ta_record_u8', 'uint16_t' => 'ta_record_u16', 'uint32_t' => 'ta_record_u32',
               'uint64_t' => 'ta_record_u64' }.freeze

    def get_prototype(info)
      text = +"#{info.type}_get decodes the #{info.msg.id} record into *out. It needs a record that ta_record_check accepted, "
      text << 'so every span is inside it and every enum and bool is in range. The scalars of *out are copies of the '
      text << "record's snapshot (not of the ring bytes, which a host may be rewriting) and may outlive the record. "
      text << 'Each ta_bytes of *out points into the record and is valid only until ta_ring_release; its bytes are '
      text << "untrusted, and text is not checked for UTF-8. TA_ERR_INVALID: the record is of another kind, and *out is untouched. "
      text << 'It never allocates and reads nothing outside record->fixed and the validated spans.'
      "#{comment(text)}ta_result #{info.type}_get(const ta_record *record, #{info.type} *out);\n\n"
    end

    def get_function(info)
      out = +"/* #{info.type}_get: see ring_proto.h. */\n"
      out << "ta_result #{info.type}_get(const ta_record *record, #{info.type} *out) {\n    #{info.type} value;\n"
      out << "    if (record->kind != #{info.kind_const}) {\n        return TA_ERR_INVALID;\n    }\n"
      out << "    ta_mem_zero(&value, sizeof value);\n"
      out << "    value.head.flags = ta_record_u16(record, TA_RECORD_AT_FLAGS);\n"
      out << "    value.head.session = ta_record_u64(record, TA_RECORD_AT_SESSION);\n"
      out << "    value.head.at = ta_record_u64(record, TA_RECORD_AT_TIME);\n"
      info.fields.each do |f|
        out << if f.span?
                 "    value.#{f.name} = ta_record_span(record, #{f.offset});\n"
               else
                 "    value.#{f.name} = #{LOADER.fetch(f.ctype)}(record, #{f.offset});\n"
               end
      end
      out << "    *out = value;\n    return TA_OK;\n}\n\n"
    end

    # ------------------------------------------------------ test support

    # tests/ring_proto_cases.h: for every message, functions that fill a data
    # struct with deterministic values (every field distinct, every enum value
    # reachable, empty and non-empty spans), compare two data structs, and call
    # size, write and get through void pointers. It lets one loop in the test
    # cover all messages without a hand-written case for each.
    def cases(model)
      infos = infos(model)
      out = +"/*\n#{wrap(GENERATED.rstrip)}\n * This file is test support: it is included by tests/ring_proto_test.c only.\n */\n"
      out << "#pragma once\n\n#define RING_PROTO_CASE_DATA_BYTES 512u\n#define RING_PROTO_CASE_POOL_BYTES 256u\n\n"
      out << CASES_PRELUDE
      infos.each { |info| out << case_functions(info) }
      out << "static const ring_proto_case ring_proto_cases[] = {\n"
      infos.each { |info| out << case_entry(info) }
      out << "};\n"
      out
    end

    CASES_PRELUDE = <<~C
      /* One message as the test loop sees it: functions over void pointers to its data struct. */
      typedef struct ring_proto_case {
          const char *id;
          uint16_t kind;
          uint32_t span_count;
          void (*fill)(void *data, uint32_t seed, const uint8_t *pool);
          bool (*equal)(const void *a, const void *b);
          ta_result (*size)(const void *data, uint32_t *size);
          ta_result (*write)(const void *data, const ta_ring_reservation *to);
          ta_result (*get)(const ta_record *record, void *out);
      } ring_proto_case;

      /* mix is a deterministic 64-bit hash of (seed, salt): splitmix64 on their concatenation. */
      static uint64_t ring_proto_mix(uint32_t seed, uint32_t salt) {
          uint64_t x = (((uint64_t)seed << 32) | salt) + 0x9E3779B97F4A7C15ull;
          x = (x ^ (x >> 30)) * 0xBF58476D1CE4E5B9ull;
          x = (x ^ (x >> 27)) * 0x94D049BB133111EBull;
          return x ^ (x >> 31);
      }

      /* view picks a span of 0..13 bytes of the pool; an empty one sometimes has a pointer and sometimes not. */
      static ta_bytes ring_proto_view(const uint8_t *pool, uint64_t x) {
          uint32_t length = (uint32_t)(x % 14u);
          uint32_t offset = (uint32_t)((x >> 8) % 200u);
          if (length == 0 && (x & 1u) != 0) {
              return (ta_bytes){ NULL, 0 };
          }
          return (ta_bytes){ pool + offset, length };
      }

      /* same says whether two views hold the same bytes; where they point does not matter. */
      static bool ring_proto_same(ta_bytes a, ta_bytes b) {
          if (a.len != b.len) {
              return false;
          }
          for (uint32_t i = 0; i < a.len; i += 1) {
              if (a.ptr[i] != b.ptr[i]) {
                  return false;
              }
          }
          return true;
      }

    C

    def case_functions(info)
      t = info.type
      out = +"/* #{info.msg.id} */\n_Static_assert(sizeof(#{t}) <= RING_PROTO_CASE_DATA_BYTES, \"#{info.msg.id} data fits the test buffer\");\n"
      out << "static void case_#{info.c}_fill(void *p, uint32_t seed, const uint8_t *pool) {\n    #{t} *d = p;\n"
      out << "    ta_mem_zero(d, sizeof *d);\n"
      out << format("    d->head.flags = (uint16_t)(ring_proto_mix(seed, 0) & 0x%04Xu);\n", info.flags_allowed)
      out << "    d->head.session = ring_proto_mix(seed, 1);\n    d->head.at = ring_proto_mix(seed, 2);\n"
      info.fields.each_with_index do |f, i|
        salt = i + 3
        out << "    d->#{f.name} = " << case_value(f, salt) << ";\n"
      end
      out << "    (void)pool;\n}\n"
      out << "static bool case_#{info.c}_equal(const void *pa, const void *pb) {\n    const #{t} *a = pa;\n    const #{t} *b = pb;\n"
      terms = ['a->head.flags == b->head.flags', 'a->head.session == b->head.session', 'a->head.at == b->head.at']
      info.fields.each do |f|
        terms << (f.span? ? "ring_proto_same(a->#{f.name}, b->#{f.name})" : "a->#{f.name} == b->#{f.name}")
      end
      out << "    return #{terms.join(" &&\n           ")};\n}\n"
      out << "static ta_result case_#{info.c}_size(const void *data, uint32_t *size) { return #{t}_size(data, size); }\n"
      out << "static ta_result case_#{info.c}_write(const void *data, const ta_ring_reservation *to) { return #{t}_write(data, to); }\n"
      out << "static ta_result case_#{info.c}_get(const ta_record *record, void *out) { return #{t}_get(record, out); }\n\n"
    end

    def case_value(field, salt)
      x = "ring_proto_mix(seed, #{salt})"
      return "ring_proto_view(pool, #{x})" if field.span?
      return "(uint8_t)(#{x} & 1u)" if field.kind == :bool

      if field.kind == :enum
        values = field.enum.values.map(&:value)
        return "(const uint8_t[]){ #{values.join(', ')} }[#{x} % #{values.size}u]"
      end
      "(#{field.ctype})#{x}"
    end

    def case_entry(info)
      "    { \"#{info.msg.id}\", #{info.kind_const}, #{info.spans.size}, case_#{info.c}_fill, case_#{info.c}_equal,\n" \
        "      case_#{info.c}_size, case_#{info.c}_write, case_#{info.c}_get },\n"
    end

    # ------------------------------------------------------- per message

    def message_header(_model, info)
      out = +message_comment(info)
      out << wire_struct(info)
      out << data_struct(info)
      out << size_prototype(info)
      out << write_prototype(info)
      out << get_prototype(info)
      out
    end

    def message_comment(info)
      msg = info.msg
      text = +"#{msg.id}: #{msg.summary}.\n\n"
      text << "#{msg.doc}\n\n" unless msg.doc.empty?
      text << "Ring #{msg.ring}, kind #{hex(msg.code)}, #{msg.fixed_size} fixed bytes, #{info.spans.size} spans. "
      text << "Replied to by #{msg.replies.join(', ')}. " if msg.replies.any?
      text << "See also #{msg.see.join(', ')}." if msg.see.any?
      text << "\n\nFields:\n"
      info.fields.each { |f| text << "  #{f.name} (#{f.type}): #{f.doc}\n" }
      msg.flags.each { |f| text << "  flag #{f.name} (bit #{f.bit}): #{f.doc}\n" }
      comment(text.rstrip)
    end

    def wire_struct(info)
      out = +"typedef struct #{info.wire} {\n    ta_msg_wire_header header;\n"
      offset = HEADER_SIZE
      info.fields.each_with_index do |f, i|
        out << "    uint8_t pad#{i}[#{f.offset - offset}];\n" if f.offset > offset
        note = f.enum ? " /* ta_msg_#{f.enum.name} */" : ''
        out << "    #{f.ctype} #{f.name};#{note}\n"
        offset = f.offset + f.size
      end
      out << "    uint8_t pad_end[#{info.msg.fixed_size - offset}];\n" if info.msg.fixed_size > offset
      out << "} #{info.wire};\n"
      out << "_Static_assert(sizeof(#{info.wire}) == #{info.msg.fixed_size}, \"#{info.msg.id}\");\n"
      info.fields.each do |f|
        out << "_Static_assert(offsetof(#{info.wire}, #{f.name}) == #{f.offset}, \"#{info.msg.id}.#{f.name}\");\n"
      end
      out << "\n"
    end

    def data_struct(info)
      out = +"typedef struct #{info.type} {\n    ta_msg_head head;\n"
      info.fields.each do |f|
        if f.span?
          out << "    ta_bytes #{f.name};\n"
        else
          note = f.enum ? " /* ta_msg_#{f.enum.name} */" : ''
          out << "    #{f.ctype} #{f.name};#{note}\n"
        end
      end
      out << "} #{info.type};\n\n"
    end
  end
