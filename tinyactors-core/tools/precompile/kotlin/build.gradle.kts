// The precompiled datamodel in Kotlin (a spike: tools/precompile). The task
// generateCharts turns every chart under src/main/scxml whose datamodel is
// "kotlin" into a Kotlin class, compiled with the application: a chart is a
// source file like any other.
import groovy.json.JsonSlurper

plugins {
    kotlin("jvm") version "2.4.21"
    kotlin("plugin.serialization") version "2.4.21"
    application
}

repositories { mavenCentral() }

dependencies {
    implementation("org.jetbrains.kotlinx:kotlinx-serialization-cbor:1.13.0")
}

kotlin { jvmToolchain(21) }

application { mainClass.set("order.MainKt") }

val generateCharts by tasks.registering {
    val charts = fileTree("src/main/scxml") { include("**/*.scxml") }
    val table = file("../../../build/release/bin/ta-precompile-table")
    val out = layout.buildDirectory.dir("generated/tinyactors")
    inputs.files(charts)
    inputs.file(table)
    outputs.dir(out)
    doLast {
        val root = out.get().asFile
        root.deleteRecursively()
        charts.visit {
            if (isDirectory) return@visit
            val process = ProcessBuilder(table.path, file.path).redirectError(ProcessBuilder.Redirect.INHERIT).start()
            val json = process.inputStream.readBytes()
            check(process.waitFor() == 0) { "ta-precompile-table refused $file" }
            // the chart's directory under src/main/scxml is its package
            val pkg = relativePath.parent.segments.joinToString(".")
            val code = kotlinOf(JsonSlurper().parse(json) as Map<*, *>, pkg, file.name)
            root.resolve(pkg.replace('.', '/')).apply { mkdirs() }.resolve(file.nameWithoutExtension + ".generated.kt").writeText(code)
        }
    }
}

kotlin.sourceSets.main { kotlin.srcDir(generateCharts) }

/** The Kotlin of the charts of one file whose datamodel is "kotlin". */
fun kotlinOf(table: Map<*, *>, pkg: String, chartFile: String): String {
    val b = StringBuilder("// Generated by generateCharts from $chartFile; do not edit.\n")
    if (pkg.isNotEmpty()) b.append("package $pkg\n")
    b.append("\nimport tinyactors.*\n")
    for (chart in table["charts"] as List<*>) {
        chart as Map<*, *>
        if (chart["datamodel"] != "kotlin") continue
        val name = chart["name"] as String
        val session = name.replaceFirstChar { it.uppercase() } + "Session"
        val expressions = (chart["expressions"] as List<*>).map { it as Map<*, *> }
        val data = (chart["data"] as List<*>).map { it as Map<*, *> }
        fun text(x: Map<*, *>) = x["text"] as String
        fun at(x: Map<*, *>) = "// $chartFile:${x["line"]}"
        fun branches(kinds: Set<String>, indent: String = "        ", each: (Map<*, *>) -> String) =
            expressions.filter { it["kind"] in kinds }.joinToString("") { "$indent${it["index"]} -> ${each(it)} ${at(it)}\n" }
        val ids = data.joinToString(", ") { "\"${it["id"]}\"" }
        b.append("\n/** A session of the chart \"$name\": its variables, and its expressions as Kotlin. */\n")
        b.append("class $session : Session() {\n")
        b.append("    companion object {\n        val chart = Chart(\"$name\", 0x${chart["fingerprint"]}uL.toLong(), listOf($ids)) { $session() }\n    }\n\n")
        for (d in data) {
            val id = d["id"]
            val x = (d["expression"] as Number?)?.let { expressions[it.toInt()] }
            b.append(if (x != null) "    private val ${id}Cell = late { ${text(x)} } ${at(x)}\n" else "    private val ${id}Cell = late { Value(UNDEFINED) }\n")
            b.append("    var $id by ${id}Cell\n")
        }
        b.append("\n    override fun initData(declaration: Int) {\n        when (declaration) {\n")
        data.forEachIndexed { i, d -> if (d["expression"] != null) b.append("            $i -> ${d["id"]}Cell.initialize()\n") }
        b.append("        }\n    }\n\n")
        b.append("    override fun setData(declaration: Int, value: Any?) {\n        when (declaration) {\n")
        data.forEachIndexed { i, d -> b.append("            $i -> ${d["id"]} = cast(value)\n") }
        b.append("        }\n    }\n\n")
        b.append("    override fun condition(expression: Int): Boolean = when (expression) {\n")
        b.append(branches(setOf("condition")) { text(it) })
        b.append("        else -> throw noExpression(expression)\n    }\n\n")
        b.append("    override fun value(expression: Int): Any? = when (expression) {\n")
        b.append(branches(setOf("value", "location", "item")) { text(it) })
        b.append("        else -> throw noExpression(expression)\n    }\n\n")
        b.append("    override fun encode(expression: Int): ByteArray = when (expression) {\n")
        b.append(branches(setOf("value", "location", "item")) { "cbor(${text(it)})" })
        b.append("        else -> throw noExpression(expression)\n    }\n\n")
        b.append("    override fun string(expression: Int): String = when (expression) {\n")
        b.append(branches(setOf("value", "location", "string")) { "text(${text(it)})" })
        b.append("        else -> throw noExpression(expression)\n    }\n\n")
        b.append("    override fun assign(location: Int, value: Any?) {\n        when (location) {\n")
        b.append(branches(setOf("location", "item"), "            ") { "${text(it)} = cast(value)" })
        b.append("            else -> throw noExpression(location)\n        }\n    }\n\n")
        b.append("    override fun script(expression: Int) {\n        when (expression) {\n")
        b.append(branches(setOf("script", "global_script"), "            ") { "{\n${text(it)}\n            }" })
        b.append("            else -> throw noExpression(expression)\n        }\n    }\n\n")
        b.append("    override fun variables() = listOf(" + data.joinToString(", ") { "\"${it["id"]}\" to ${it["id"]}Cell.encode()" } + ")\n\n")
        b.append("    override fun setVariables(variables: Value) {\n")
        for (d in data) b.append("        variables[\"${d["id"]}\"].let { if (it.isDefined) ${d["id"]}Cell.decode(it.bytes) }\n")
        b.append("    }\n}\n")
    }
    return b.toString()
}
