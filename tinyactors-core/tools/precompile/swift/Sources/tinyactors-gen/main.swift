// tinyactors-gen writes the Swift code of the charts in an .scxml file
// whose datamodel is "swift" (a spike: tools/precompile). The build plugin
// runs it for every .scxml file of a target:
//
//   tinyactors-gen <ta-precompile-table> <chart.scxml> <output.swift>
//
// Per chart, a subclass of Session: each <data> a lazy property, typed by
// its expression (the compiler infers it), and each expression a case of a
// switch, with #sourceLocation at the chart's line, so the compiler's errors
// and warnings name the chart's lines.
import Foundation

struct Table: Decodable {
    struct Chart: Decodable {
        struct Data: Decodable { let id: String; let expression: Int? }
        let name: String, datamodel: String, fingerprint: String
        let data: [Data]
        let expressions: [Expression]
    }
    struct Expression: Decodable { let index: Int, kind: String, line: Int, column: Int, text: String }
    let charts: [Chart]
}

let arguments = CommandLine.arguments
guard arguments.count == 4 else {
    FileHandle.standardError.write("usage: tinyactors-gen ta-precompile-table chart.scxml output.swift\n".data(using: .utf8)!)
    exit(2)
}
let chartPath = URL(fileURLWithPath: arguments[2]).standardizedFileURL.path
let process = Process()
process.executableURL = URL(fileURLWithPath: arguments[1])
process.arguments = [chartPath]
let pipe = Pipe()
process.standardOutput = pipe
try process.run()
let raw = pipe.fileHandleForReading.readDataToEndOfFile()
process.waitUntilExit()
guard process.terminationStatus == 0 else { exit(1) }
let table = try JSONDecoder().decode(Table.self, from: raw)

var out = "// Generated by tinyactors-gen from \((chartPath as NSString).lastPathComponent); do not edit.\nimport Tinyactors\n"

/// one statement of the chart's code, at its line in the chart
func at(_ x: Table.Expression, _ statement: String) -> String {
    "#sourceLocation(file: \"\(chartPath)\", line: \(x.line))\n            \(statement)\n#sourceLocation()\n"
}

for chart in table.charts where chart.datamodel == "swift" {
    let session = chart.name.prefix(1).uppercased() + chart.name.dropFirst() + "Session"
    let expressions = chart.expressions
    func cases(_ kinds: Set<String>, _ each: (Table.Expression) -> String) -> String {
        expressions.filter { kinds.contains($0.kind) }.map { "        case \($0.index):\n" + at($0, each($0)) }.joined()
    }
    let ids = chart.data.map { "\"\($0.id)\"" }.joined(separator: ", ")
    out += """

    /// A session of the chart "\(chart.name)": its variables, and its expressions as Swift.
    final class \(session): Session {
        static let chart = Chart(name: "\(chart.name)", fingerprint: 0x\(chart.fingerprint), data: [\(ids)], make: { \(session)() })


    """
    for d in chart.data {
        if let x = d.expression {
            out += at(expressions[x], "lazy var \(d.id) = \(expressions[x].text)").replacingOccurrences(of: "            lazy", with: "    lazy")
        } else {
            out += "    lazy var \(d.id) = Value(.undefined)\n"
        }
    }
    out += "\n    override func initData(_ declaration: Int) throws {\n        switch declaration {\n"
    for (i, d) in chart.data.enumerated() {
        guard let x = d.expression else { continue }
        out += "        case \(i):\n" + at(expressions[x], "\(d.id) = \(expressions[x].text)")
    }
    out += "        default: break\n        }\n    }\n\n"
    out += "    override func setData(_ declaration: Int, _ value: Any) throws {\n        switch declaration {\n"
    for (i, d) in chart.data.enumerated() {
        out += "        case \(i): \(d.id) = try cast(value)\n"
    }
    out += "        default: break\n        }\n    }\n\n"
    out += "    override func condition(_ expression: Int) throws -> Bool {\n        switch expression {\n"
    out += cases(["condition"]) { "return \($0.text)" }
    out += "        default: throw noExpression(expression)\n        }\n    }\n\n"
    out += "    override func value(_ expression: Int) throws -> Any {\n        switch expression {\n"
    out += cases(["value", "location", "item"]) { "return \($0.text)" }
    out += "        default: throw noExpression(expression)\n        }\n    }\n\n"
    out += "    override func encode(_ expression: Int) throws -> [UInt8] {\n        switch expression {\n"
    out += cases(["value", "location", "item"]) { "return try cbor(\($0.text))" }
    out += "        default: throw noExpression(expression)\n        }\n    }\n\n"
    out += "    override func string(_ expression: Int) throws -> String {\n        switch expression {\n"
    out += cases(["value", "location", "string"]) { "return text(\($0.text))" }
    out += "        default: throw noExpression(expression)\n        }\n    }\n\n"
    out += "    override func assign(_ location: Int, _ value: Any) throws {\n        switch location {\n"
    out += cases(["location", "item"]) { "\($0.text) = try cast(value)" }
    out += "        default: throw noExpression(location)\n        }\n    }\n\n"
    out += "    override func script(_ expression: Int) throws {\n        switch expression {\n"
    out += cases(["script", "global_script"]) { $0.text }
    out += "        default: throw noExpression(expression)\n        }\n    }\n\n"
    out += "    override func variables() throws -> [(String, CBOR)] {\n        [" +
        chart.data.map { "(\"\($0.id)\", try variableTree(\($0.id)))" }.joined(separator: ", ") + "]\n    }\n\n"
    out += "    override func setVariables(_ variables: Value) throws {\n"
    for d in chart.data {
        out += "        if variables.\(d.id).isDefined { \(d.id) = try variables.\(d.id).decode() }\n"
    }
    out += "    }\n}\n"
}
try out.write(toFile: arguments[3], atomically: true, encoding: .utf8)
