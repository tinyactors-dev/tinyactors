# frozen_string_literal: true

module Changelog
  # A component's CHANGELOG.md. Each release is a section:
  #
  #   ## [0.2.0] - 2026-10-05
  #
  #   ### Summary          written by the agent, reviewed by the maintainer
  #   ### Upgrading        written, present when the release breaks something
  #   <!-- generated ... -->
  #   ### Breaking changes  generated from the evidence: the commits,
  #   ### API changes       the API delta,
  #   ### Changes           and the rest of the commits.
  #   ### Internal
  #
  # Below the marker nothing is written by hand: `changelog:check` renders
  # it again from the repository and fails when the file differs.
  module Document
    MARKER = '<!-- Generated by `mise run changelog:write`. Do not edit below: `mise run changelog:check` renders it again. -->'
    HEADING = /^## \[(?<version>[^\]]+)\] - (?<date>\d{4}-\d{2}-\d{2})[ \t]*$/

    Section = Struct.new(:version, :date, :text, :summary, :upgrading, :generated, keyword_init: true)

    module_function

    def preamble(component)
      <<~TEXT
        # #{component.title}

        What changed in #{component.dir} in each release. The summary of a release
        is written for someone upgrading; the lists below it are generated from the
        commits and from the public API (docs/adr/0002-changelogs.md).

      TEXT
    end

    # The sections of a file, newest (topmost) first.
    def sections(text)
      matches = text.to_enum(:scan, HEADING).map { Regexp.last_match }
      matches.each_with_index.map do |match, index|
        stop = matches[index + 1]&.begin(0) || text.size
        parse(match[:version], match[:date], text[match.begin(0)...stop])
      end
    end

    def section(text, version) = sections(text).find { |candidate| candidate.version == version }

    def parse(version, date, text)
      written, generated = text.split(MARKER, 2)
      Section.new(version: version, date: date, text: text,
                  summary: part(written, 'Summary'), upgrading: part(written, 'Upgrading'),
                  generated: generated && generated.strip)
    end

    # The body under `### name`, up to the next `### ` heading.
    def part(text, name)
      body = text[/^### #{name}[ \t]*\n(.*?)(?=^### |\z)/m, 1]
      body&.strip
    end

    # The section for `version`, assembled from the prose and the evidence.
    def render(evidence, version:, date:, summary:, upgrading: nil)
      out = ["## [#{version}] - #{date}", '', '### Summary', '', summary.strip, '']
      out += ['### Upgrading', '', upgrading.strip, ''] if upgrading && !upgrading.strip.empty?
      generated = render_generated(evidence)
      out += [MARKER, '', generated, ''] unless generated.empty?
      "#{out.join("\n").rstrip}\n"
    end

    # The generated part of a section, rendered from the evidence alone.
    def render_generated(evidence)
      groups = Ledger.grouped(evidence.commits)
      out = []
      unless groups[:breaking].empty?
        out << '### Breaking changes' << ''
        out.concat(groups[:breaking].map { |commit| Ledger.line(commit) })
        out << ''
      end
      out.concat(api_lines(evidence.delta))
      unless groups[:changes].empty?
        out << '### Changes' << ''
        groups[:changes].each do |heading, commits|
          out << "**#{heading}**" << ''
          out.concat(commits.map { |commit| Ledger.line(commit) })
          out << ''
        end
      end
      unless groups[:internal].empty?
        out << '<details>' << "<summary>Internal (#{groups[:internal].size})</summary>" << ''
        out.concat(groups[:internal].map { |commit| Ledger.line(commit) })
        out << '' << '</details>' << ''
      end
      out.join("\n").strip
    end

    def api_lines(delta)
      return [] if delta.empty?

      out = ['### API changes', '']
      { 'Removed' => delta.removed, 'Added' => delta.added }.each do |heading, entities|
        next if entities.empty?

        out << "**#{heading}**" << ''
        out.concat(entities.map { |entity| "- #{entity.kind} `#{entity.name}`" })
        out << ''
      end
      unless delta.changed.empty?
        out << '**Changed**' << ''
        out.concat(delta.changed.map { |entity, _old| "- #{entity.kind} `#{entity.name}`" })
        out << ''
      end
      out
    end

    # `file_text` with `section` first: replaces the section of the same
    # version, else goes above the newest one.
    def insert(file_text, component, version, section)
      file_text = preamble(component) if file_text.nil? || file_text.strip.empty?
      existing = sections(file_text).find { |candidate| candidate.version == version }
      return file_text.sub(existing.text) { "#{section}\n" } if existing

      first = file_text.index(HEADING)
      return "#{file_text.rstrip}\n\n#{section}" unless first

      "#{file_text[0...first]}#{section}\n#{file_text[first..]}"
    end

    # What a release publishes: the section without its heading or marker.
    def release_body(section)
      body = section.text.sub(HEADING, '').sub(MARKER, '')
      "#{body.gsub(/\n{3,}/, "\n\n").strip}\n"
    end
  end
end
