# frozen_string_literal: true

require 'fileutils'
require 'pathname'
require 'rexml/document'
require_relative 'document'

module ScxmlIrp
  # One <assert> of vendor/scxml-irp/manifest.xml and its test.
  Test = Data.define(:id, :section, :conformance, :manual, :assertion, :starts, :deps) do
    def label = "test#{id}"
    def mandatory? = conformance == 'mandatory'
  end

  # The outcome of importing one test: the generated scenario file, which
  # defines the test's charts and its scenarios, or the reason it is skipped.
  Import = Data.define(:test, :charts, :source, :skip_reason, :notes) do
    def imported? = skip_reason.nil?
  end

  # Converts the vendored W3C SCXML IRP suite into scenario files for the
  # scenario runner. Each test's file defines the machines the test needs
  # (the test document, its child machines, and its sub-documents) followed
  # by the scenarios that run them.
  class Importer
    GENERATED = 'Generated by `mise run import-scxml-irp`. Do not edit; change ruby/scxml_irp instead.'

    def initialize(suite:, scenarios_dir:, root:)
      @suite = Pathname.new(suite)
      @scenarios_dir = Pathname.new(scenarios_dir)
      @root = Pathname.new(root)
    end

    def tests
      manifest = REXML::Document.new(@suite.join('manifest.xml').read)
      manifest.root.elements.to_a('assert').map do |assert|
        test = assert.elements['test']
        Test.new(id: assert.attributes['id'],
                 section: assert.attributes['specnum'],
                 conformance: test.attributes['conformance'],
                 manual: test.attributes['manual'] == 'true',
                 assertion: assert.children.grep(REXML::Text).map(&:value).join.strip.gsub(/\s+/, ' '),
                 starts: test.elements.to_a('start').map { |start| start.attributes['uri'] },
                 deps: test.elements.to_a('dep').map { |dep| dep.attributes['uri'] })
      end.sort_by { |test| test.id.to_i }
    end

    def import(test)
      reason = skip_reason(test)
      return skipped(test, reason) if reason

      notes = []
      charts = []
      sources = []
      test.deps.select { |dep| dep.end_with?('.txml') }.each do |dep|
        name = "irp_#{File.basename(dep, '.txml')}"
        sources << convert(test, dep, name, top_level: false, notes: notes)
        charts << name
      end
      starts = test.starts.map do |start|
        name = "irp_#{File.basename(start, '.txml')}"
        sources << convert(test, start, name, top_level: true, notes: notes)
        charts << name
        [File.basename(start, '.txml'), name]
      end

      Import.new(test: test, charts: charts, source: scenario_file(test, sources, starts),
                 skip_reason: nil, notes: notes.uniq)
    rescue Unsupported => e
      skipped(test, e.message)
    end

    # Imports every test, replaces the generated files, and returns the
    # imports.
    def write_all
      imports = tests.map { |test| import(test) }
      FileUtils.mkdir_p(@scenarios_dir)
      Dir[@scenarios_dir.join('*.rb').to_s].each { |file| File.delete(file) }
      imports.select(&:imported?).each do |import|
        @scenarios_dir.join("#{import.test.label}.rb").write(import.source)
      end
      @scenarios_dir.join('INDEX.md').write(index(imports))
      imports
    end

    private

    def skipped(test, reason)
      Import.new(test: test, charts: [], source: nil, skip_reason: reason, notes: [])
    end

    def skip_reason(test)
      return 'manual test: a person judges its log output' if test.manual

      sources = (test.starts + test.deps).select { |uri| uri.end_with?('.txml') }.map { |uri| @suite.join(uri).read }
      if sources.any? { |source| source.match?(/BasicHTTPEventProcessor|conf:basicHTTP|conf:testOnServer/) }
        return 'needs the optional BasicHTTP Event I/O Processor (SCXML C.2)'
      end

      nil
    end

    def convert(test, uri, chart_name, top_level:, notes:)
      path = @suite.join(uri)
      directory = path.dirname
      resolve = lambda do |src|
        file = src.sub(/\Afile:/, '')
        raise Unsupported, "<data src=#{src.inspect}> is not a local file" if file.include?('/') || file.include?(':')

        dependency = directory.join(file)
        raise Unsupported, "<data src=#{src.inspect}> is missing from the suite" unless dependency.file?

        dependency.read
      end
      document = Document.new(Document.parse(path), chart_name: chart_name, top_level: top_level,
                                                    resolve_file: resolve)
      source = document.convert
      notes.concat(document.notes, document.child_notes)
      source
    rescue REXML::ParseException => e
      raise Unsupported, "#{uri} is not well-formed XML: #{e.message.lines.first.strip}"
    end

    def relative(uri) = @suite.join(uri).relative_path_from(@root).to_s

    def header(test, uris)
      lines = ['# frozen_string_literal: true', '', "# #{GENERATED}", '#']
      lines << "# W3C SCXML IRP assertion #{test.id} (section #{test.section}, #{test.conformance}):"
      wrap(test.assertion, 74).each { |line| lines << "#   #{line}" }
      lines << '#'
      uris.each { |uri| lines << "# Source: #{relative(uri)}" }
      lines.join("\n")
    end

    def scenario_file(test, sources, starts)
      uris = test.deps.select { |dep| dep.end_with?('.txml') } + test.starts
      emitter = Emitter.new
      emitter.block("TinyactorsTest.scenarios 'scxml-irp'") do
        starts.each_with_index do |(label, chart_name), index|
          emitter.line if index.positive?
          emitter.line("ScxmlIrp.expect_failure(self, #{Ruby.str(label)})")
          emitter.block("scenario #{Ruby.str(label)}") do
            emitter.line("machine = spawn #{Ruby.sym(chart_name)}")
            emitter.line('run_to_completion machine')
            emitter.line("assert_equal 'pass', machine.data('.#{Document::OUTCOME}')")
          end
        end
      end
      "#{header(test, uris)}\n\nrequire_relative '../../scxml_irp/expectations'\n\n" \
        "#{sources.join("\n")}\n#{emitter}"
    end

    def index(imports)
      imported = imports.count(&:imported?)
      lines = ['# W3C SCXML IRP import', '', "<!-- #{GENERATED} -->", '']
      lines << "#{imported} of #{imports.size} tests imported; #{imports.size - imported} skipped."
      lines << ''
      counts = imports.group_by { |import| [import.test.conformance, import.imported?] }.transform_values(&:size)
      lines << '| Conformance | Imported | Skipped |'
      lines << '|---|---|---|'
      %w[mandatory optional].each do |conformance|
        lines << "| #{conformance} | #{counts.fetch([conformance, true], 0)} | #{counts.fetch([conformance, false], 0)} |"
      end
      lines << ''
      lines << '## Skip reasons'
      lines << ''
      reasons = imports.reject(&:imported?).group_by { |import| reason_category(import.skip_reason) }
      reasons.sort_by { |_, list| -list.size }.each do |category, list|
        lines << "- #{category}: #{list.size}"
      end
      lines << ''
      lines << '## Tests'
      lines << ''
      lines << '| Test | Section | Conformance | Status | Details |'
      lines << '|---|---|---|---|---|'
      imports.each do |import|
        test = import.test
        status = import.imported? ? 'imported' : 'skipped'
        details = import.imported? ? import.notes.join('; ') : import.skip_reason
        lines << "| #{test.id} | #{test.section} | #{test.conformance} | #{status} | #{details.to_s.gsub('|', '\\|')} |"
      end
      "#{lines.join("\n")}\n"
    end

    def reason_category(reason)
      case reason
      when /\Amanual/ then 'manual test'
      when /BasicHTTP/ then 'BasicHTTP Event I/O Processor'
      when /XML DOM/ then 'XML DOM in the ECMAScript data model'
      when /data model/ then 'other data model'
      when /ECMAScript/, /cannot translate/, /call of/ then 'ECMAScript expression or script'
      else reason
      end
    end

    def wrap(text, width)
      text.split.each_with_object([+'']) do |word, lines|
        if lines.last.empty? then lines.last << word
        elsif lines.last.length + word.length + 1 > width then lines << word.dup
        else lines.last << " #{word}"
        end
      end
    end
  end
end
