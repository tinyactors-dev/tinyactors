# frozen_string_literal: true

require 'json'

module RPC
  # Formats a Plan as C. It makes no decisions: every name, key, codec, and
  # condition comes from the plan. Decoders return false after recording an
  # error with its path; encoders return an owned jv.
  class Emit
    PREAMBLE = <<~C
      typedef struct {
          const char *name;
          long long value;
      } tat_enum_entry;

      static bool tat_enum_decode(tat_bind *b, jv in, const tat_enum_entry *entries, size_t count,
                                  const char *names, long long *out) {
          if (jv_get_kind(in) == JV_KIND_STRING) {
              for (size_t index = 0; index < count; index += 1) {
                  if (strcmp(entries[index].name, jv_string_value(in)) == 0) {
                      *out = entries[index].value;
                      return true;
                  }
              }
          }
          return tat_fail(b, "expected one of: %s", names);
      }

      static jv tat_enum_encode(const tat_enum_entry *entries, size_t count, long long value) {
          for (size_t index = 0; index < count; index += 1) {
              if (entries[index].value == value) {
                  return jv_string(entries[index].name);
              }
          }
          return jv_number((double)value);
      }

      /* Adds a member; with omit_null, absent (null) values are left out. */
      static void tat_put(jv *o, const char *key, jv value, bool omit_null) {
          if (!jv_is_valid(value)) {
              jv_free(value);
              value = jv_null();
          }
          if (omit_null && jv_get_kind(value) == JV_KIND_NULL) {
              jv_free(value);
              return;
          }
          *o = jv_object_set(*o, jv_string(key), value);
      }
    C

    def initialize(api, plan)
      @api = api
      @plan = plan
      @decls = []
      @defs = []
    end

    def header
      emit
      <<~C
        /* GENERATED by `mise run bindings` from tinyactors.api.json. Do not edit. */
        #pragma once

        #include "binding.h"

        #{@decls.join("\n")}

        extern const tat_method TAT_GENERATED_METHODS[];
        extern const size_t TAT_GENERATED_METHOD_COUNT;
      C
    end

    def source
      emit
      table = @plan.methods.sort_by(&:name).map do |method|
        "    {#{method.name.to_json}, #{method.handler}, #{JSON.generate(method.schema).to_json}},"
      end
      receivers = @plan.receivers.map { |rpc, member, model| "    {#{rpc.to_json}, #{member.to_json}, #{model}}," }
      receivers = ['    {NULL, NULL, TAT_VALUE_MODEL_ACTOR},'] if receivers.empty?
      <<~C
        /* GENERATED by `mise run bindings` from tinyactors.api.json. Do not edit. */
        #include "ta_rpc.h"

        #include <string.h>

        #{PREAMBLE}
        #{@defs.join("\n")}
        const tat_method TAT_GENERATED_METHODS[] = {
        #{table.join("\n")}
        };

        const size_t TAT_GENERATED_METHOD_COUNT = sizeof(TAT_GENERATED_METHODS) / sizeof(TAT_GENERATED_METHODS[0]);

        /* Methods whose ta_value inputs belong to the data model of an actor or definition. */
        const tat_value_receiver TAT_VALUE_RECEIVERS[] = {
        #{receivers.join("\n")}
        };

        const size_t TAT_VALUE_RECEIVER_COUNT = #{@plan.receivers.size};
      C
    end

    private

    def emit
      return if @emitted

      @emitted = true
      @plan.enums.each { |name| enum(name) }
      @plan.structs.each_value { |struct| self.struct(struct) }
      @plan.lists.each_value { |list| terminated(list) }
      @plan.arrays.each_value { |list| counted(list) }
      @plan.methods.each do |method|
        case method.kind
        when :external then external(method)
        when :function then self.method(method)
        end
      end
    end

    def block(lines, indent = 1) = lines.map { |line| line.empty? ? line : "#{'    ' * indent}#{line}" }.join("\n")

    # ------------------------------------------------------------------
    # Enums: symbols come from the API description.

    def enum(name)
      constants = @api.type(name)['constants']
      table = constants.map { |constant| "{#{constant['symbol'].to_json}, #{constant['name']}}" }
      names = constants.map { |constant| constant['symbol'] }.join(', ')
      @decls << "bool tat_decode_#{name}(tat_bind *b, jv in, #{name} *out);"
      @decls << "jv tat_encode_#{name}(tat_bind *b, const #{name} *in);"
      @defs << <<~C
        static const tat_enum_entry TAT_ENUM_#{name}[] = {#{table.join(', ')}};

        bool tat_decode_#{name}(tat_bind *b, jv in, #{name} *out) {
            long long value = 0;
            if (!tat_enum_decode(b, in, TAT_ENUM_#{name}, #{constants.size}, #{names.to_json}, &value)) return false;
            *out = (#{name})value;
            return true;
        }

        jv tat_encode_#{name}(tat_bind *b, const #{name} *in) {
            (void)b;
            return tat_enum_encode(TAT_ENUM_#{name}, #{constants.size}, (long long)*in);
        }
      C
    end

    # ------------------------------------------------------------------
    # Members

    def keys(name, keys) = "static const char *const #{name}[] = {#{(keys.map(&:to_json) + ['NULL']).join(', ')}};"

    # Statements decoding member `field` of object `in` into `prefix`.
    def decode(field, prefix)
      target = "#{prefix}#{field.access}"
      statements = case field.form
                   when :value then ["bool ok = #{field.codec.decode('v', "&#{target}")};"]
                   when :pointer
                     ["#{field.ctype} *p = tat_alloc(b, sizeof(#{field.ctype}), _Alignof(#{field.ctype}));",
                      "bool ok = p != NULL && #{field.codec.decode('v', 'p')};",
                      "#{target} = p;"]
                   when :handle
                     ['void *h = NULL;', "bool ok = tat_handle_resolve(b, v, #{field.handle.to_json}, &h);", "#{target} = h;"]
                   when :view then ['bool ok = tat_fail(b, "borrowed views cannot be supplied");']
                   when :list then ["bool ok = tat_decode_list_#{field.list.key}(b, v, &#{target});"]
                   when :array then ["bool ok = tat_decode_array_#{field.list.key}(b, v, &#{target}, &#{prefix}#{field.count});"]
                   end
      key = field.key.to_json
      lines = ["if (tat_member(in, #{key}, &v)) {", *statements.map { |line| "    #{line}" }, '    jv_free(v);',
               "    if (!ok) return tat_at(b, #{key});"]
      if field.required
        lines << "} else {" << '    tat_fail(b, "missing member");' << "    return tat_at(b, #{key});" << '}'
      else
        lines << '}'
      end
      lines
    end

    # Statements adding member `field` of `prefix` to object `*o`.
    def encode(field, prefix, omit)
      source = "#{prefix}#{field.access}"
      value = case field.form
              when :value
                return ["if (#{source}) tat_put(o, #{field.key.to_json}, #{field.codec.encode("&#{source}")}, true);"] if omit && field.zero_omittable

                field.codec.encode("&#{source}")
              when :pointer then "#{source} ? #{field.codec.encode(source)} : jv_null()"
              when :handle then "tat_handle_encode(b, #{field.handle.to_json}, #{source})"
              when :view then "tat_borrowed_encode(#{field.handle.to_json}, #{source})"
              when :list then "tat_encode_list_#{field.list.key}(b, #{source})"
              when :array then "tat_encode_array_#{field.list.key}(b, #{source}, #{prefix}#{field.count})"
              end
      ["tat_put(o, #{field.key.to_json}, #{value}, #{omit});"]
    end

    # ------------------------------------------------------------------
    # Structs

    def struct(struct)
      name = struct.name
      @decls << "bool tat_decode_#{name}(tat_bind *b, jv in, #{name} *out);"
      @decls << "jv tat_encode_#{name}(tat_bind *b, const #{name} *in);"
      @decls << "bool tat_fields_#{name}(tat_bind *b, jv in, #{name} *out);"
      @decls << "void tat_put_fields_#{name}(tat_bind *b, const #{name} *in, jv *o);"
      omit = struct.zero_is_absent
      decode = struct.fields.flat_map { |field| decode(field, 'out->') }
      decode.concat(struct.arenas.map { |arena| "out->#{arena} = &b->arena;" })
      encode = struct.fields.flat_map { |field| encode(field, 'in->', omit) }
      check = []
      if (tagged = struct.tagged)
        decode.concat(tagged_decode(struct, tagged))
        encode.unshift("if (in->#{tagged.tag} == 0) return;") if omit
        encode.concat(tagged_encode(tagged))
      else
        check = [keys('keys', struct.fields.map(&:key)), 'if (!tat_check_keys(b, in, keys)) return false;']
      end
      @defs << <<~C
        bool tat_fields_#{name}(tat_bind *b, jv in, #{name} *out) {
            jv v = jv_invalid();
            (void)b;
            (void)v;
        #{block(decode)}
            return true;
        }

        bool tat_decode_#{name}(tat_bind *b, jv in, #{name} *out) {
            memset(out, 0, sizeof(*out));
            if (!tat_expect_object(b, in)) return false;
        #{block(check)}
            return tat_fields_#{name}(b, in, out);
        }

        void tat_put_fields_#{name}(tat_bind *b, const #{name} *in, jv *o) {
            (void)b;
            (void)in;
            (void)o;
        #{block(encode)}
        }

        jv tat_encode_#{name}(tat_bind *b, const #{name} *in) {
        #{block(omit && tagged ? ["if (in->#{tagged.tag} == 0) return jv_null();"] : [])}
            jv o = jv_object();
            tat_put_fields_#{name}(b, in, &o);
            return o;
        }

        static jv tat_roundtrip_#{name}(tat_bind *b, jv params, int *error_code) {
            static const char *const keys[] = {"value", NULL};
            jv value = jv_invalid();
            if (!tat_check_keys(b, params, keys)) return tat_bind_take_error(b, error_code);
            if (!tat_member(params, "value", &value)) {
                tat_fail(b, "missing member");
                tat_at(b, "value");
                return tat_bind_take_error(b, error_code);
            }
            #{name} *decoded = tat_alloc(b, sizeof(#{name}), _Alignof(#{name}));
            bool ok = decoded != NULL && tat_decode_#{name}(b, value, decoded);
            jv_free(value);
            if (!ok) {
                tat_at(b, "value");
                return tat_bind_take_error(b, error_code);
            }
            return tat_encode_#{name}(b, decoded);
        }
      C
    end

    def tagged_decode(struct, tagged)
      tag = tagged.tag
      infer = tagged.inferable.map do |key, constant|
        "if (!have_kind && tat_member(in, #{key.to_json}, &v)) { jv_free(v); out->#{tag} = #{constant}; have_kind = true; }"
      end
      missing = if tagged.kind_required
                  ["if (!have_kind) { tat_fail(b, \"missing member\"); return tat_at(b, #{tag.to_json}); }"]
                else
                  ['(void)have_kind;']
                end
      cases = tagged.kinds.reject { |kind| kind.layout == :none }.flat_map do |kind|
        members = case kind.layout
                  when :keyed then decode(kind.keyed, 'out->')
                  when :inline then kind.fields.flat_map { |field| decode(field, 'out->') }
                  when :named then ["if (!tat_fields_#{kind.named}(b, in, &out->#{kind.access})) return false;"]
                  end
        ["case #{kind.constant}: {", "    #{keys('keys', kind.keys)}", '    if (!tat_check_keys(b, in, keys)) return false;',
         *members.map { |line| "    #{line}" }, '    break;', '}']
      end
      default_keys = struct.fields.map(&:key) + [tag]
      [
        '{',
        '    bool have_kind = false;',
        "    if (tat_member(in, #{tag.to_json}, &v)) {",
        "        bool ok = tat_decode_#{tagged.enum}(b, v, &out->#{tag});",
        '        jv_free(v);',
        "        if (!ok) return tat_at(b, #{tag.to_json});",
        '        have_kind = true;',
        '    }',
        *infer.map { |line| "    #{line}" },
        *missing.map { |line| "    #{line}" },
        "    switch (out->#{tag}) {",
        *cases.map { |line| "    #{line}" },
        '    default: {',
        "        #{keys('keys', default_keys)}",
        '        if (!tat_check_keys(b, in, keys)) return false;',
        '        break;',
        '    }',
        '    }',
        '}'
      ]
    end

    def tagged_encode(tagged)
      tag = tagged.tag
      cases = tagged.kinds.reject { |kind| kind.layout == :none }.flat_map do |kind|
        members = case kind.layout
                  when :keyed then encode(kind.keyed, 'in->', false)
                  when :inline then kind.fields.flat_map { |field| encode(field, 'in->', false) }
                  when :named then ["tat_put_fields_#{kind.named}(b, &in->#{kind.access}, o);"]
                  end
        ["case #{kind.constant}:", *members.map { |line| "    #{line}" }, '    break;']
      end
      ["tat_put(o, #{tag.to_json}, tat_encode_#{tagged.enum}(b, &in->#{tag}), false);",
       "switch (in->#{tag}) {", *cases, 'default:', '    break;', '}']
    end

    # ------------------------------------------------------------------
    # Lists

    def terminated(list)
      ctype = list.element
      @decls << "bool tat_decode_list_#{list.key}(tat_bind *b, jv in, const #{ctype} **out);"
      @decls << "jv tat_encode_list_#{list.key}(tat_bind *b, const #{ctype} *in);"
      @defs << <<~C
        static bool tat_end_#{list.key}(const #{ctype} *item) {
            return #{list.terminator};
        }

        bool tat_decode_list_#{list.key}(tat_bind *b, jv in, const #{ctype} **out) {
            size_t length = 0;
            if (!tat_expect_array(b, in, &length)) return false;
            /* One extra zeroed element terminates the list. */
            #{ctype} *items = tat_alloc_array(b, length + 1, sizeof(#{ctype}), _Alignof(#{ctype}));
            if (items == NULL) return false;
            for (size_t index = 0; index < length; index += 1) {
                jv item = jv_array_get(jv_copy(in), (int)index);
                bool ok = #{list.codec.decode('item', '&items[index]')};
                jv_free(item);
                if (ok && tat_end_#{list.key}(&items[index])) ok = tat_fail(b, "element would terminate the list");
                if (!ok) return tat_at_index(b, index);
            }
            *out = items;
            return true;
        }

        jv tat_encode_list_#{list.key}(tat_bind *b, const #{ctype} *in) {
            if (in == NULL) return jv_null();
            jv array = jv_array();
            for (const #{ctype} *item = in; !tat_end_#{list.key}(item); item += 1) {
                array = jv_array_append(array, #{list.codec.encode('item')});
            }
            return array;
        }
      C
    end

    def counted(list)
      ctype = list.element
      count = list.count_ctype
      @decls << "bool tat_decode_array_#{list.key}(tat_bind *b, jv in, const #{ctype} **out, #{count} *count);"
      @decls << "jv tat_encode_array_#{list.key}(tat_bind *b, const #{ctype} *in, #{count} count);"
      @defs << <<~C
        bool tat_decode_array_#{list.key}(tat_bind *b, jv in, const #{ctype} **out, #{count} *count) {
            size_t length = 0;
            if (!tat_expect_array(b, in, &length)) return false;
            if ((size_t)(#{count})length != length) return tat_fail(b, "too many elements");
            #{ctype} *items = tat_alloc_array(b, length, sizeof(#{ctype}), _Alignof(#{ctype}));
            if (items == NULL) return false;
            for (size_t index = 0; index < length; index += 1) {
                jv item = jv_array_get(jv_copy(in), (int)index);
                bool ok = #{list.codec.decode('item', '&items[index]')};
                jv_free(item);
                if (!ok) return tat_at_index(b, index);
            }
            *out = items;
            *count = (#{count})length;
            return true;
        }

        jv tat_encode_array_#{list.key}(tat_bind *b, const #{ctype} *in, #{count} count) {
            if (in == NULL) return jv_null();
            jv array = jv_array();
            for (#{count} index = 0; index < count; index += 1) {
                array = jv_array_append(array, #{list.codec.encode('&in[index]')});
            }
            return array;
        }
      C
    end

    # ------------------------------------------------------------------
    # Methods

    def external(method)
      @decls << "jv tat_handler_#{method.function}(tat_bind *b, jv params, int *error_code);"
    end

    def method(method)
      name = method.function
      storage = method.storage.empty? ? ['char unused;'] : method.storage
      decode = []
      unless method.flattened
        decode << keys('keys', method.keys) << 'if (!tat_check_keys(b, in, keys)) return false;'
      end
      decode.concat(method.fields.flat_map { |field| decode(field, 'a->') })
      if (flattened = method.flattened)
        param, struct = flattened
        decode << 'jv sub = jv_copy(in);'
        method.keys.each { |key| decode << "sub = jv_object_delete(sub, jv_string(#{key.to_json}));" }
        decode << "bool decoded = tat_decode_#{struct.name}(b, sub, &a->#{param});" << 'jv_free(sub);'
        decode << 'if (!decoded) return false;'
      end
      decode.concat(method.outputs.flat_map(&:setup))
      @defs << <<~C
        typedef struct {
        #{block(storage)}
        } tat_args_#{name};

        static bool tat_prepare_#{name}(tat_bind *b, jv in, tat_args_#{name} *a) {
            jv v = jv_invalid();
            (void)v;
            (void)a;
        #{block(decode)}
            return true;
        }

        static jv tat_method_#{name}(tat_bind *b, jv params, int *error_code) {
            tat_args_#{name} args;
            tat_args_#{name} *a = &args;
            memset(a, 0, sizeof(*a));
            if (!tat_prepare_#{name}(b, params, a)) return tat_bind_take_error(b, error_code);
        #{block(method.implemented ? call(method) : ["return tat_not_implemented(b, #{name.to_json}, error_code);"])}
        }
      C
    end

    def call(method)
      result = method.result
      invocation = "#{method.function}(#{method.call_args.join(', ')})"
      lines = case result[:kind]
              when :status
                ["#{result[:ctype]} r = #{invocation};",
                 "jv result = jv_object_set(jv_object(), jv_string(\"result\"), #{result[:codec].encode('&r')});"]
              when :value
                ["#{result[:ctype]} r = #{invocation};",
                 "jv result = jv_object_set(jv_object(), jv_string(\"value\"), #{result[:codec].encode('&r')});"]
              else
                ["#{invocation};", 'jv result = jv_object();']
              end
      unless method.outputs.empty?
        lines << 'jv out = jv_object();'
        method.outputs.each { |output| lines << "out = jv_object_set(out, jv_string(#{output.key.to_json}), #{output.encode});" }
        lines << 'result = jv_object_set(result, jv_string("out"), out);'
      end
      method.outputs.each { |output| lines.concat(output.releases) }
      method.retire.each do |handle, on|
        lines << (on ? "if (r == #{on}) tat_handle_retire(b, #{handle});" : "tat_handle_retire(b, #{handle});")
      end
      lines << 'return result;'
    end
  end
end
