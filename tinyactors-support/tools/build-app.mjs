// Build the issue list's single HTML file (lib/app/issues.html) from its
// source (lib/app/source/) and the tinyactors design system's tokens
// (.agents/skills/tinyactors-design/tokens/), all inline: an MCP App's view
// loads nothing (the host's default CSP: no connect, no external styles,
// scripts or fonts). The tokens' dark theme applies under
// [data-theme="dark"], which the app sets from the host's theme, and under
// prefers-color-scheme when the host says none. No fonts are embedded: the
// default CSP has no font-src, so the tokens' fallback stacks (system-ui,
// ui-monospace) are what renders.
//
//   node tools/build-app.mjs           writes lib/app/issues.html
//   node tools/build-app.mjs --check   fails when it is out of date
import { readFileSync, writeFileSync } from 'node:fs';

const here = (path) => new URL(path, import.meta.url);
const TOKENS = ['colors', 'typography', 'spacing', 'effects'];
export const OUTPUT = here('../lib/app/issues.html');

export function buildApp() {
  const tokens = TOKENS.map((name) => readFileSync(here(`../../.agents/skills/tinyactors-design/tokens/${name}.css`), 'utf8'))
    .join('\n');
  // every [data-theme="dark"] block again, for a host that gives no theme and a dark system
  const dark = [...tokens.matchAll(/\[data-theme="dark"\]\{([^}]*)\}/g)].map((m) => m[1]).join('');
  const themed = `${tokens}\n@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){${dark}}}`;
  const style = readFileSync(here('../lib/app/source/style.css'), 'utf8');
  const script = readFileSync(here('../lib/app/source/app.js'), 'utf8').replaceAll('</script', '<\\/script');
  return readFileSync(here('../lib/app/source/issues.html'), 'utf8')
    .replace('/*TOKENS*/', () => `/* tinyactors design system tokens (generated by tools/build-app.mjs) */\n${themed}`)
    .replace('/*STYLE*/', () => style).replace('/*SCRIPT*/', () => script);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const html = buildApp();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUTPUT, 'utf8') !== html) { console.error('lib/app/issues.html is out of date: node tools/build-app.mjs'); process.exit(1); }
  } else {
    writeFileSync(OUTPUT, html);
    console.log(`lib/app/issues.html: ${html.length} bytes`);
  }
}
