// The report of `mise run bench-engines`, in Markdown, from the records of
// one run (compare.mjs's, between the task's `run` and `end` records):
//
//   node report.mjs RECORDS > report.md
//
// It gives the machine, the versions, the method, the time per op of each
// engine with ratios to staticjs, their geometric means, the start-up
// costs, the memory and the caveats. Nothing in it is written by hand: to
// change the report, change this file and rerun the task.
import { readFileSync } from 'node:fs';

const records = readFileSync(process.argv[2], 'utf8').trim().split('\n').filter(Boolean).map(line => JSON.parse(line));
const only = kind => records.filter(r => r.kind === kind);
const runInfo = only('run')[0] ?? {};
const end = only('end')[0] ?? {};
const settings = only('settings')[0];
if (!settings) throw new Error('no measured records (compare.mjs measure did not run)');
const times = only('time');
const ENGINES = ['staticjs', 'node', 'node-jitless', 'quickjs-wasi'];
const TITLES = { staticjs: 'staticjs', node: 'Node JIT', 'node-jitless': 'Node --jitless', 'quickjs-wasi': 'quickjs-wasi' };

const median = xs => { const s = [...xs].sort((a, b) => a - b); const m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const digits = x => (x >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x >= 1 ? x.toFixed(2) : x.toFixed(3));
const percent = x => `${(x * 100).toFixed(x < 0.1 ? 1 : 0)}%`;
const kib = x => (x === undefined || x === null ? 'n/a' : `${(x / 1024).toFixed(1)} KiB`);
const factor = r => (r >= 10 ? r.toFixed(0) : r.toFixed(1));
const ratio = (staticjs, other) => {
  const r = other / staticjs;
  return r >= 1 ? `${factor(r)}× faster` : `${factor(1 / r)}× slower`;
};
const cell = text => String(text).replace(/\|/g, '\\|');

// Per case and engine: the median of the rounds' figures, and the range of
// the middle rounds (all of them when there are fewer than four).
const rows = [];
for (const name of settings.cases) {
  const rs = times.filter(r => r.case === name);
  if (rs.length === 0) continue;
  const n = rs[0].n;
  const staticjsRecord = rs.find(r => r.engine === 'staticjs' && !r.error);
  const unit = rs.find(r => r.unit)?.unit === 'element' ? 'element' : 'op';
  const per = {}, range = {}, errors = [];
  for (const engine of ENGINES) {
    const mine = rs.filter(r => r.engine === engine);
    errors.push(...mine.filter(r => r.error).map(r => `${TITLES[engine]} round ${r.round}: ${r.error}`));
    const ok = mine.filter(r => !r.error).map(r => r.nsPerOp).sort((a, b) => a - b);
    if (ok.length === 0) continue;
    const units = unit === 'element' ? n : 1;
    const middle = ok.length >= 4 ? ok.slice(1, -1) : ok;
    const m = median(ok);
    per[engine] = m / units;
    range[engine] = { lo: middle[0] / units, hi: middle[middle.length - 1] / units, spread: (middle[middle.length - 1] - middle[0]) / m,
      full: (ok[ok.length - 1] - ok[0]) / m, runs: ok.length };
  }
  rows.push({ name, n, unit, per, range, errors, bytes: name.startsWith('compile.') ? staticjsRecord?.unitsPerOp : null,
    staticjsRecord });
}

const out = [];
const line = (...xs) => out.push(...xs);
const partial = settings.quick || settings.filter;
const commit = `${runInfo.commit ?? '?'}${runInfo.dirty ? ' (dirty)' : ''}`;

line('# staticjs and other JavaScript engines', '');
line(`Generated by \`mise run bench-engines\` on ${runInfo.time ?? '?'} (UTC), staticjs ${commit}, machine ` +
  `\`${runInfo.machine ?? '?'}\`. Do not edit: rerun the task (staticjs/README.md, "Benchmarks").`, '');
if (partial) {
  line(`**A partial run** (${[settings.quick ? '--quick' : null, settings.filter ? `cases starting with \`${settings.filter}\`` : null]
    .filter(Boolean).join(', ')}): for a quick look, not for comparing.`, '');
}

line('## Machine and versions', '');
line('| | |', '|---|---|');
line(`| machine signature | \`${runInfo.machine ?? '?'}\` (bench/results/README.md) |`);
for (const [key, value] of Object.entries(runInfo.fields ?? {})) line(`| ${cell(key)} | ${cell(value)} |`);
const load = c => (c?.loadAverage ? c.loadAverage.map(x => x.toFixed(2)).join(' / ') : 'n/a');
line(`| load average (1 / 5 / 15 min) before | ${load(runInfo.conditionsBefore)} |`);
line(`| load average (1 / 5 / 15 min) after | ${load(end.conditionsAfter)} |`);
if (runInfo.conditionsBefore?.cpuSpeedLimit != null) {
  line(`| CPU speed limit before / after | ${runInfo.conditionsBefore.cpuSpeedLimit} / ${end.conditionsAfter?.cpuSpeedLimit} |`);
}
const staticjsVersion = times.find(r => r.staticjsVersion)?.staticjsVersion;
const quickjsVersions = times.find(r => r.versions)?.versions ?? {};
line(`| staticjs | commit ${commit}, sjs_version() ${staticjsVersion ?? '?'}, build/release/bench (pinned clang, ${runInfo.fields?.flags ?? '?'}) |`);
line(`| Node | ${settings.node} (V8 ${settings.v8}) |`);
line(`| quickjs-wasi | ${quickjsVersions['quickjs-wasi'] ?? '?'} (QuickJS-NG ${quickjsVersions.quickjs ?? '?'}, WebAssembly run by Node's V8) |`);
line(`| run | ${settings.rounds} rounds, ${settings.samples} samples of ≥ ${settings.sampleMs} ms each after ` +
  `${settings.warmupNodeMs} ms (Node, quickjs-wasi) or ${settings.warmupStaticjsMs} ms (staticjs) of warm-up; ` +
  `${end.seconds ? `${(end.seconds / 60).toFixed(1)} min in all` : ''} |`, '');

line('## Method', '');
line(
  '- **The cases** are bench/bench.c\'s own (listed in bench/engines/cases.mjs, with the size each runs at): the ' +
  'same source, the same globals, the same fixtures. bench/engines/dump.c reads them from bench.c; the JavaScript ' +
  'engines build the fixtures with bench/engines/guest.js, which mirrors bench.c\'s generators.',
  '- **Verified before timing.** For every case, at its smoke size and at the measured size, each fixture as ' +
  'staticjs\'s writer writes it (from bench.c\'s own generators) has the same length and FNV-1a hash as guest.js\'s ' +
  'in each engine; each engine\'s result has the same length and hash as staticjs\'s; and at the smoke size each ' +
  'engine\'s result prints as bench.c\'s expected value. A difference stops the run, naming the case (the ' +
  'Verification section lists what was checked).',
  '- **staticjs** is build/release/bench (`mise run bench`\'s build), run as `bench --only=CASE --size=N`: per op, ' +
  'sjs_vm_start, run, take the result, release it, with the program compiled once and the globals bound once; ' +
  'the figure of a run is the median of its samples.',
  '- **Node JIT and Node --jitless** run a guest program (bench/engines/guest.mjs: guest.js, the fixtures, and ' +
  'the case\'s source as an arrow function) evaluated once in the runner\'s realm. One sample is one call ' +
  '`__bench.run(k)`, which calls the case k times inside the engine and adds up a fold of each result (its ' +
  'length, size or value), so that no engine can drop the work. The host clock is read around that call.',
  '- **quickjs-wasi** runs the same guest program in QuickJS-NG compiled to WebAssembly (the npm package, pinned ' +
  'in bench/engines/package-lock.json), in a fresh instance per process; one sample is one `evalCode("__bench.run(k)")`, ' +
  'so the crossing between the host and the guest is paid once per sample, not per op.',
  `- **Calibration.** In every engine k grows (×8 while a sample takes under a tenth of the target, then ×2) until ` +
  `one sample takes at least ${settings.sampleMs} ms; then the warm-up, then ${settings.samples} samples, whose ` +
  'median is the run\'s figure.',
  `- **Interleaved rounds.** Each case runs ${settings.rounds} rounds; a round runs the four engines one after ` +
  'another, each in a process of its own, never two at once: staticjs, Node, Node --jitless, quickjs-wasi, and the ' +
  'next round in the reverse order, so that a drift of the machine does not favour one engine. A cell is the ' +
  'median of the rounds\' figures.',
  '- **Spread and ≈.** Each engine\'s range is that of its middle rounds (the fastest and the slowest dropped, ' +
  'with four rounds or more; all of them otherwise). A cell shows ±half that range, as a percentage of the ' +
  'median, when the range exceeds 10%. A ratio is marked ≈ when staticjs\'s range and the other engine\'s ' +
  'overlap: that ratio is not resolved, and the two may be equal.',
  '- **Ratios** are the other engine\'s time divided by staticjs\'s: "2.0× faster" means staticjs takes half the ' +
  'time of that engine, "2.0× slower" twice the time.',
  '');

line('## Time per op', '');
line('| case | n | unit | staticjs | Node JIT | Node --jitless | quickjs-wasi | vs Node JIT | vs --jitless | vs quickjs-wasi |',
  '|---|---:|---|---:|---:|---:|---:|---|---|---|');
for (const r of rows) {
  const scale = r.unit === 'element' ? 1 : 1e-3;
  const value = e => (r.per[e] === undefined ? 'n/a'
    : digits(r.per[e] * scale) + (r.range[e].spread > 0.10 ? ` ±${(r.range[e].spread * 50).toFixed(0)}%` : ''));
  const versus = e => {
    if (r.per[e] === undefined || r.per.staticjs === undefined) return 'n/a';
    const overlap = r.range.staticjs.lo <= r.range[e].hi && r.range[e].lo <= r.range.staticjs.hi;
    return ratio(r.per.staticjs, r.per[e]) + (overlap ? ' (≈)' : '');
  };
  const n = r.bytes ? `${r.bytes} B` : r.n;
  line(`| ${r.name} | ${n} | ${r.unit === 'element' ? 'ns/elem' : 'µs/op'} | ${ENGINES.map(value).join(' | ')} | ` +
    `${['node', 'node-jitless', 'quickjs-wasi'].map(versus).join(' | ')} |`);
}
line('');
const evalRows = rows.filter(r => r.name.startsWith('eval.'));
const geo = e => {
  const xs = evalRows.filter(r => r.per[e] && r.per.staticjs).map(r => Math.log(r.per[e] / r.per.staticjs));
  return xs.length ? Math.exp(xs.reduce((a, b) => a + b, 0) / xs.length) : NaN;
};
line(`**Geometric means** over the ${evalRows.length} eval.* rows of (engine time / staticjs time), above 1 when ` +
  `staticjs is faster: Node JIT **${geo('node').toFixed(2)}**, Node --jitless **${geo('node-jitless').toFixed(2)}**, ` +
  `quickjs-wasi **${geo('quickjs-wasi').toFixed(2)}**.`, '');
line(`**Spread** of the middle rounds, per engine (median and largest over the rows; in parentheses the median of ` +
  `the full range, slowest round to fastest): ${ENGINES.map(e => {
    const s = rows.filter(r => r.range[e]).map(r => r.range[e].spread);
    const f = rows.filter(r => r.range[e]).map(r => r.range[e].full);
    return s.length ? `${TITLES[e]} ${percent(median(s))}, max ${percent(Math.max(...s))} (${percent(median(f))})` : `${TITLES[e]} n/a`;
  }).join('; ')}.`, '');
const failed = rows.filter(r => r.errors.length);
if (failed.length) {
  line('**Runs that failed** (their rounds are left out above):', '');
  for (const r of failed) for (const e of r.errors) line(`- ${r.name}: ${cell(e)}`);
  line('');
}

line('## Start-up and per-evaluation overhead', '');
line('The guard is eval.guard.event\'s source, its globals bound once; each row is one op, timed as above in ' +
  'rounds of its own.', '');
line('| what | engine | includes | median | rounds (range) |', '|---|---|---|---:|---|');
const startup = only('startup');
const seen = new Set();
for (const r of startup) {
  const key = `${r.label}|${r.engine}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const mine = startup.filter(s => `${s.label}|${s.engine}` === key);
  const v = mine.filter(s => !s.error).map(s => s.nsPerOp);
  const us = x => `${(x / 1000).toFixed(3)} µs`;
  line(`| ${cell(r.label)} | ${TITLES[r.engine]} | ${cell(r.includes)} | ${v.length ? us(median(v)) : 'failed'} | ` +
    `${v.length}${v.length ? ` (${us(Math.min(...v))} – ${us(Math.max(...v))})` : `: ${cell(mine[0].error)}`} |`);
}
line('');

line('## Memory', '');
line('| case | n | staticjs inputs (setupBytes) | staticjs peak/op | staticjs held | quickjs-wasi fixtures | quickjs-wasi held | Node held (indicative) |',
  '|---|---:|---:|---:|---:|---:|---:|---:|');
const memory = only('memory');
for (const r of evalRows) {
  const m = r.staticjsRecord?.memory;
  const q = memory.find(x => x.case === r.name && x.engine === 'quickjs-wasi' && x.n === r.n && !x.error);
  const q1 = memory.find(x => x.case === r.name && x.engine === 'quickjs-wasi' && x.n === 1 && !x.error);
  const nd = memory.find(x => x.case === r.name && x.engine === 'node' && x.n === r.n && !x.error);
  line(`| ${r.name} | ${r.n} | ${kib(m?.setupBytes)} | ${kib(m?.peakBytes)} | ${kib(m?.heldBytes)} | ` +
    `${r.n > 1 && q && q1 ? kib(q.afterFixtures - q1.afterFixtures) : 'n/a'} | ${kib(q?.heldBytes)} | ${kib(nd?.heldBytes)} |`);
}
line('');
line(
  '- **staticjs** counts every byte through the bench\'s allocator, in one untimed op: setupBytes is everything ' +
  'live after setup (the context, the compiled program and the inputs, so about 100 KiB at n = 1), peak is the ' +
  'op\'s transient high-water mark above that, held is what its result keeps while held.',
  '- **quickjs-wasi** is QuickJS\'s own malloc accounting (`getMemoryUsage().mallocSize`) after a full collection: ' +
  'fixtures is what the guest program holds at n beyond what it holds at n = 1, held what one result adds while ' +
  'held. It has no peak.',
  '- **Node** is heapUsed + external after two full collections (--expose-gc), around holding one result: the ' +
  'runner\'s own objects share that heap and collections are not exact, so it is only indicative and can be negative.',
  '- The three represent values differently (staticjs\'s values, QuickJS\'s JSValues and shapes, V8\'s ' +
  'tagged pointers and hidden classes), so equal work need not take equal bytes.',
  '');

line('## Caveats', '');
line(
  '- **Compile rows are lazy in V8.** `new Function(source)` makes V8 pre-parse the inner functions and compile ' +
  'only the outer one; a function is compiled when first called. staticjs and QuickJS compile every function to ' +
  'their bytecode at once. The compile rows therefore favour Node.',
  '- **Modules are emulated.** The guest is a script, so power.js and campaign.js run as function bodies (exports ' +
  'become consts, the import is dropped). eval.module.power runs that body each op in the JavaScript engines; ' +
  'staticjs evaluates its compiled module program.',
  '- **One call per op in staticjs, one loop in the guest elsewhere.** staticjs\'s op is a whole embedder ' +
  'evaluation (start, run, take the result, release); the other engines\' op is a call of a function inside a ' +
  'warm loop, which a JIT can inline and specialise. The start-up table gives what one evaluation from the host ' +
  'costs in each.',
  '- **Noise.** Figures move by several percent between processes and by more between days; compare runs from one ' +
  'machine signature and one day only, and read nothing into a ratio marked ≈.',
  '- **Not a conformance claim.** The cases are the subset staticjs supports; the other engines run full JavaScript.',
  '');

line('## Verification', '');
const verified = only('verify');
if (verified.length) {
  line('| case | sizes checked | result at the measured size |', '|---|---|---|');
  for (const v of verified) {
    line(`| ${v.case} | ${v.sizes.join(', ')} | ${v.result ? `${v.result.len} chars, FNV-1a ${v.result.hash}` : 'n/a'}` +
      `${v.problems.length ? ` — FAILED: ${cell(v.problems.join('; '))}` : ''} |`);
  }
} else {
  line('No verification records (the task always verifies before timing).');
}
process.stdout.write(`${out.join('\n')}\n`);
