import { execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const { chromium } = createRequire(execFileSync('npm', ['root', '-g'], { encoding: 'utf8' }).trim() + '/')('playwright');
const dir = new URL('.', import.meta.url).pathname;
const server = createServer(async (q, s) => { const p = new URL(q.url, 'http://x').pathname; if (p === '/') return s.writeHead(200, { 'content-type': 'text/html' }).end('<!doctype html><body>');
  try { s.writeHead(200, { 'content-type': p.endsWith('.wasm') ? 'application/wasm' : 'text/javascript' }).end(await readFile(dir + p.slice(1))); } catch { s.writeHead(404).end(); } });
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const browser = await chromium.launch();
const page = await browser.newPage(); await page.goto(`http://127.0.0.1:${server.address().port}/`);
const r = await page.evaluate(async () => { const { strings } = await import('/str2.mjs'); const { semantics } = await import('/realms2.mjs'); const { detach } = await import('/detach.mjs'); return { detach: detach(), strings: await strings(await (await fetch('/calls.wasm')).arrayBuffer()), semantics: semantics() }; });
await browser.close(); server.close();
const { strings } = await import('./str2.mjs');
console.log(JSON.stringify({ chromium: r, [typeof Bun !== 'undefined' ? 'bun' : 'node']: await strings(readFileSync(dir + 'calls.wasm')) }, null, 1));
