// docs/surprises.md, the catalogue of the surprises the example
// applications found (docs/plan.xml, p4-surprises), generated from
// docs/log.xml's entries of kind="surprise" so that it never drifts from
// the log: each one's example, what happened, the layers it lived in
// (the entry's `layer`), and its fix with the commits its resolution
// names, or why it is left for the maintainer.
//
//   node tools/surprises.mjs           writes docs/surprises.md
//   node tools/surprises.mjs --check   fails when the file is not what the
//                                      log gives, or a surprise is open or
//                                      has no layer or no resolution
//
// mise run lint runs the check. The log is edited with tools/planxml.py
// (lxml, validated against docs/log.rng); this reads it with a parser
// for that schema's shape only: entries of attributes and text elements.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LOG = `${ROOT}docs/log.xml`;
const OUT = `${ROOT}docs/surprises.md`;
const LAYERS = ['core', 'binding', 'docs'];

const ENTITIES = { lt: '<', gt: '>', amp: '&', quot: '"', apos: "'" };
const unescape = (text) =>
  text.replace(/&(#x[0-9a-fA-F]+|#[0-9]+|[a-z]+);/g, (whole, name) => {
    if (name.startsWith('#x')) return String.fromCodePoint(parseInt(name.slice(2), 16));
    if (name.startsWith('#')) return String.fromCodePoint(parseInt(name.slice(1), 10));
    if (!(name in ENTITIES)) throw new Error(`docs/log.xml: unknown entity ${whole}`);
    return ENTITIES[name];
  });

/** The entries of docs/log.xml: their attributes and their text elements. */
export function entries(xml) {
  const found = [];
  for (const [, attributes, body] of xml.matchAll(/<entry\b([^>]*)>([\s\S]*?)<\/entry>/g)) {
    const entry = {};
    for (const [, name, value] of attributes.matchAll(/([\w-]+)="([^"]*)"/g)) entry[name] = unescape(value);
    for (const [, name, text] of body.matchAll(/<(what|why|evidence|resolution)>([\s\S]*?)<\/\1>/g)) entry[name] = unescape(text);
    found.push(entry);
  }
  return found;
}

/** The first sentence of `text`: up to a full stop followed by a capital. */
const first = (text) => /^([\s\S]+?[.!?])\s+(?=[A-Z`(])/.exec(text)?.[1] ?? text;
/** The commits `text` names: hexadecimal words of 7 to 12 with a digit and a letter. */
const commits = (text) => [...new Set((text ?? '').match(/\b(?=[0-9a-f]*[0-9])(?=[0-9a-f]*[a-f])[0-9a-f]{7,12}\b/g) ?? [])];
/** `text` on one line, as Markdown that shows it as it is written. */
const oneLine = (text) =>
  text.replace(/\s+/g, ' ').trim().replace(/[\\`*_[\]]/g, (c) => `\\${c}`).replace(/</g, '&lt;').replace(/>/g, '&gt;');

const outcome = (entry) => {
  if (entry.status === 'for-maintainer') return 'for the maintainer';
  return entry.layer === 'docs' ? 'documented' : 'fixed';
};

/** The problems that keep the catalogue from being complete. */
function problems(surprises) {
  const found = [];
  for (const entry of surprises) {
    if (entry.status === 'open') found.push(`${entry.id} is open: resolve it, or mark it for-maintainer with a reason`);
    if (!entry.resolution) found.push(`${entry.id} has no resolution`);
    if (!entry.example) found.push(`${entry.id} names no example`);
    const layers = (entry.layer ?? '').split(/\s+/).filter(Boolean);
    if (layers.length === 0) found.push(`${entry.id} has no layer`);
    for (const layer of layers) if (!LAYERS.includes(layer)) found.push(`${entry.id}: unknown layer ${layer}`);
  }
  return found;
}

/** docs/surprises.md for the log's entries. */
export function catalogue(all) {
  const byID = new Map(all.map((entry) => [entry.id, entry]));
  const surprises = all.filter((entry) => entry.kind === 'surprise');
  const count = (key) => {
    const counts = new Map();
    for (const entry of surprises) for (const value of key(entry)) counts.set(value, (counts.get(value) ?? 0) + 1);
    return counts;
  };
  const layers = count((entry) => (entry.layer ?? '').split(/\s+/).filter(Boolean));
  const outcomes = count((entry) => [outcome(entry)]);
  const lines = [
    '# Surprises',
    '',
    '<!-- Generated by tools/surprises.mjs from docs/log.xml; do not edit. Run `node tools/surprises.mjs` after a change to the log. -->',
    '',
    'The example applications (`examples/`) were written as a newcomer would',
    'write them, and each thing that did not work as the documentation led',
    'its author to expect is a surprise, logged in `docs/log.xml`. This is',
    'every one of them: what happened, where it lived (core, the binding or',
    'its documentation), and how it was fixed, or why it is left for the',
    'maintainer.',
    '',
    `${surprises.length} surprises in ${new Set(surprises.map((entry) => entry.example)).size} examples.`,
    '',
    '| Layer | Surprises |',
    '|---|---|',
    ...LAYERS.map((layer) => `| ${layer} | ${layers.get(layer) ?? 0} |`),
    '',
    'A surprise that lived in two layers counts in both.',
    '',
    '| Outcome | Surprises |',
    '|---|---|',
    ...['fixed', 'documented', 'for the maintainer'].map((name) => `| ${name} | ${outcomes.get(name) ?? 0} |`),
    '',
  ];
  const examples = [...new Set(surprises.map((entry) => entry.example))];
  for (const example of examples) {
    lines.push(`## ${example}`, '');
    for (const entry of surprises.filter((s) => s.example === example)) {
      const named = commits(entry.resolution);
      lines.push(`### \`${entry.id}\``, '');
      lines.push(`- **What happened:** ${oneLine(first(entry.what))}`);
      lines.push(`- **Where:** ${(entry.layer ?? '').split(/\s+/).join(', ')}`);
      lines.push(`- **Outcome:** ${outcome(entry)}`);
      if (entry.status === 'for-maintainer') lines.push(`- **Why it is left:** ${oneLine(entry.resolution)}`);
      else lines.push(`- **Fix:** ${oneLine(first(entry.resolution))}`);
      if (named.length) lines.push(`- **Commits:** ${named.join(', ')}`);
      const related = [...new Set(entry.resolution.match(/\bl-[a-z0-9-]+\b/g) ?? [])]
        .filter((id) => id !== entry.id && byID.get(id)?.status === 'for-maintainer');
      for (const id of related) lines.push(`- **Left for the maintainer, \`${id}\`:** ${oneLine(byID.get(id).what)}`);
      lines.push('');
    }
  }
  return { text: lines.join('\n'), problems: problems(surprises) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { text, problems: found } = catalogue(entries(readFileSync(LOG, 'utf8')));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {}
    if (current !== text) found.push('docs/surprises.md is not what docs/log.xml gives: run node tools/surprises.mjs');
    for (const problem of found) console.error(`surprises: ${problem}`);
    if (found.length) process.exit(1);
    console.log('surprises: docs/surprises.md is current, and every surprise is resolved or for the maintainer');
  } else {
    writeFileSync(OUT, text);
    for (const problem of found) console.error(`surprises: ${problem}`);
    console.log(`surprises: wrote docs/surprises.md`);
  }
}
