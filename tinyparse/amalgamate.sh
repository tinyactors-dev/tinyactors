#!/usr/bin/env bash
# amalgamate.sh — fold tinyparse into a single-file distribution under
# dist/amalgamation/.
#
# The amalgamation is a "dumb concatenation": cat the sources together in a
# stable, dependency-ordered sequence and strip the handful of #include lines
# that name files whose contents are now inlined. It produces three sources and
# a build note:
#
#   tinyparse.h      verbatim copy of the public header
#   tinyparse.c      one translation unit: the public header + internal.h +
#                      every library .c except cli.c
#   tinyparse_cli.c  the CLI, with the embedded manpage inlined
#   README.md          how to build the three files
#
# The library depends on nothing: it is freestanding C with its own arena
# allocator, so the amalgamation is the library alone.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="$HERE/src"
INC="$HERE/include"
OUT="$HERE/dist/amalgamation"

V="$(cat "$HERE/VERSION")"

log() { printf '[tp-amalgamate] %s\n' "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }

mkdir -p "$OUT"

# --- ensure the generated manpage header exists for the CLI ------------------
# cli.c #includes "manpage_data.h", a build artifact. Generate it via build.sh
# if it is not already present.
if [ ! -f "$SRC/manpage_data.h" ] || [ ! -f "$SRC/grammars_data.h" ] || \
   [ ! -f "$SRC/amalgamation_data.h" ]; then
  log "generated CLI headers missing; generating via build.sh dist"
  ( cd "$HERE" && bash build.sh dist ) >/dev/null 2>&1 || true
fi
[ -f "$SRC/manpage_data.h" ]      || die "manpage_data.h still missing after build.sh"
[ -f "$SRC/grammars_data.h" ]     || die "grammars_data.h still missing after build.sh"
[ -f "$SRC/amalgamation_data.h" ] || die "amalgamation_data.h still missing after build.sh"

# --- helper: drop the inlined-file #include lines ----------------------------
# Strips only the local "..." includes whose targets are folded in. System
# <...> includes are left untouched.
strip_inlined_includes() {
  grep -vE '^[[:space:]]*#[[:space:]]*include[[:space:]]+"(tinyparse\.h|internal\.h|manpage_data\.h)"' "$@"
}

# --- tinyparse.h: verbatim public header -----------------------------------
cp "$INC/tinyparse.h" "$OUT/tinyparse.h"

# --- tinyparse.c: the single translation unit ------------------------------
{
  cat <<EOF
/*
** tinyparse.c -- single-file amalgamation of the tinyparse library.
**
** GENERATED by amalgamate.sh for tinyparse $V.
** Do not edit by hand. It folds together, in one translation unit:
**   - the tinyparse public header;
**   - the private internal.h contract;
**   - every library source (each C file in src/ except the CLI).
**
** Build:  cc -c tinyparse.c
**         cc -shared -fPIC -fvisibility=hidden tinyparse.c -o libtinyparse.so
*/

/*
** The tinyparse library is built with default visibility so its public
** symbols are exported even when the whole file is compiled with
** -fvisibility=hidden (the recommended shared-library flag).
*/
#pragma GCC visibility push(default)

/* ===== tinyparse public header ========================================== */
EOF
  cat "$INC/tinyparse.h"
  printf '\n/* ===== tinyparse internal header ======================================== */\n'
  strip_inlined_includes "$SRC/internal.h"

  # Library sources in a stable (sorted) order, cli.c excluded.
  for c in $(ls "$SRC"/*.c | sort); do
    base="$(basename "$c")"
    [ "$base" = "cli.c" ] && continue
    printf '\n/* ===== src/%s ============================================ */\n' "$base"
    strip_inlined_includes "$c"
  done
  printf '\n#pragma GCC visibility pop\n'
} > "$OUT/tinyparse.c"

# --- tinyparse_cli.c: the CLI with the manpage inlined ---------------------
# Keep #include "tinyparse.h" (shipped alongside). Replace the
# #include "manpage_data.h" line with the contents of the generated header so
# the CLI carries its embedded manual without that build artifact.
{
  cat <<EOF
/*
** tinyparse_cli.c -- the tinyparse command-line shell (amalgamated).
**
** GENERATED by amalgamate.sh for tinyparse $V.
** It keeps #include "tinyparse.h" (shipped alongside) and links against
** tinyparse.c / libtinyparse. The embedded manual page header is inlined
** below, replacing the generated manpage_data.h.
**
** Build:  cc tinyparse.c tinyparse_cli.c -o tinyparse
*/
EOF
  while IFS= read -r line; do
    case "$line" in
      '#include "manpage_data.h"')
        printf '\n/* --- inlined manpage_data.h --- */\n'
        cat "$SRC/manpage_data.h"
        printf '/* --- end manpage_data.h --- */\n'
        ;;
      '#include "grammars_data.h"')
        printf '\n/* --- inlined grammars_data.h --- */\n'
        cat "$SRC/grammars_data.h"
        printf '/* --- end grammars_data.h --- */\n'
        ;;
      '#include "amalgamation_data.h"')
        printf '\n/* --- inlined amalgamation_data.h --- */\n'
        cat "$SRC/amalgamation_data.h"
        printf '/* --- end amalgamation_data.h --- */\n'
        ;;
      *)
        printf '%s\n' "$line"
        ;;
    esac
  done < "$SRC/cli.c"
} > "$OUT/tinyparse_cli.c"

# --- README.md: build instructions -------------------------------------------
cat > "$OUT/README.md" <<EOF
# tinyparse $V — single-file amalgamation

This directory is the single-file distribution of tinyparse. Drop the two
sources and the header into your project; they need only a C99 compiler and the
freestanding headers \`<stddef.h>\` and \`<stdint.h>\`.

| File | Role |
|------|------|
| \`tinyparse.h\` | the public header — the only interface you include |
| \`tinyparse.c\` | the whole library in one translation unit |
| \`tinyparse_cli.c\` | the optional command-line front end, with its manual page embedded |

## Build

\`\`\`sh
# the library object
cc -c tinyparse.c

# the command-line tool
cc tinyparse.c tinyparse_cli.c -o tinyparse

# a shared library exporting the public tinyparse_* API
cc -shared -fPIC -fvisibility=hidden tinyparse.c -o libtinyparse.so
\`\`\`

Include \`tinyparse.h\` from your own code and link against the object, the
shared library, or \`tinyparse.c\` directly.
EOF

log "wrote amalgamation to $OUT ($(wc -c < "$OUT/tinyparse.c") bytes tinyparse.c)"
